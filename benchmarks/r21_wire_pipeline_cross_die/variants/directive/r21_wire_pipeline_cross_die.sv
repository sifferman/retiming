// r21 -- wire_pipeline_cross_die  (DIRECTIVE VARIANT)
//
//   din --[ cluster A: 4 lanes x 3 rounds ]--> (a_q : 64 bits) ==== bus ====> [ cluster B ] --> (b_q) --> PO
//
// Two substantial logic clusters joined by a 64-bit bus.  Each cluster is large
// enough that the placer cannot merge them, so after placement the bus spans a
// significant fraction of the die and its wire delay -- not the logic -- sets the
// achievable period.
//
// The transform that fixes this is to pipeline the bus.  That ADDS a cycle of
// latency, so it is NOT a retiming: no legal assignment of retiming lags can
// insert a register that was not already somewhere on the path.
//
// That is exactly why this case is interesting for the project.  A
// placement-driven retimer can see the problem and cannot legally fix it; fixing
// it requires a latency contract with the surrounding design.  This benchmark
// quantifies what that permission is worth.
//
// Because the reference changes latency, equivalence is checked with a one-cycle
// skew (scripts/check_equiv.py --skew 1) rather than cycle-for-cycle.

module r21_wire_pipeline_cross_die_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [63:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  // Cluster A lane: three rounds on a lane-specific mix of the input.
  function automatic logic [15:0] fa (input logic [15:0] x, input int i);
    logic [15:0] v;
    v  = x ^ 16'(i * 16'h9E37);
    fa = rnd(rnd(rnd(v, 16'h9E37, 16'h1234), 16'h7B15, 16'h5A5A), 16'hC2B2, 16'h0F1E);
  endfunction

  // Cluster B lane: three more rounds, consuming the bus.
  function automatic logic [15:0] fb (input logic [15:0] x, input int i);
    logic [15:0] v;
    v  = x ^ 16'(i * 16'h7F4A);
    fb = rnd(rnd(rnd(v, 16'h27D4, 16'hBEEF), 16'h1656, 16'h3C3C), 16'h6763, 16'h07E1);
  endfunction

  logic [63:0] a_q, b_q;

  // Cluster A
  always_ff @(posedge clk) begin
    if (!rst_n) a_q <= 64'h0;
    else begin
      for (int i = 0; i < 4; i++) a_q[i*16 +: 16] <= fa(din, i);
    end
  end

  // Cluster B consumes the bus directly -- the long wire is on this path.
  always_ff @(posedge clk) begin
    if (!rst_n) b_q <= 64'h0;
    else begin
      for (int i = 0; i < 4; i++) b_q[i*16 +: 16] <= fb(a_q[i*16 +: 16], i);
    end
  end

  assign dout = b_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r21_wire_pipeline_cross_die_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r21_wire_pipeline_cross_die (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [63:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [63:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r21_wire_pipeline_cross_die_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
