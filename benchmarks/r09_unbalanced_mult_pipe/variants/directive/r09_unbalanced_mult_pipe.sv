// r09 -- unbalanced_mult_pipe  (DIRECTIVE VARIANT)
// Original RTL; the retiming is requested from the tool instead of hand-coded.
//
// Three register stages, but essentially all of the combinational work sits in
// stage 1: the full 16x16 product is formed there, then stages 2 and 3 do an add
// and an xor.  The register cut is maximally unbalanced.
//
// This is the textbook Leiserson-Saxe case and is included as a POSITIVE
// CONTROL: a retimer that cannot fix this is not conservative, it is broken.

module r09_unbalanced_mult_pipe_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] a,
    input  logic [15:0] b,
    input  logic [31:0] c,
    output logic [31:0] dout
);

  logic [31:0] s1_q, s2_q, s3_q;

  // Stage 1: the entire multiply.  This is the critical path.
  always_ff @(posedge clk) begin
    if (!rst_n) s1_q <= 32'h0;
    else        s1_q <= a * b;
  end

  // Stage 2: one add.
  always_ff @(posedge clk) begin
    if (!rst_n) s2_q <= 32'h0;
    else        s2_q <= s1_q + c;
  end

  // Stage 3: one xor.
  always_ff @(posedge clk) begin
    if (!rst_n) s3_q <= 32'h0;
    else        s3_q <= s2_q ^ 32'hA5A5_5A5A;
  end

  assign dout = s3_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r09_unbalanced_mult_pipe_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r09_unbalanced_mult_pipe (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] a,
    input  logic [15:0] b,
    input  logic [31:0] c,
    output logic [31:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] a_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] b_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [31:0] c_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [31:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      a_iq <= '0;
      b_iq <= '0;
      c_iq <= '0;
    end else begin
      a_iq <= a;
      b_iq <= b;
      c_iq <= c;
    end
  end

  r09_unbalanced_mult_pipe_core u_core (
    .clk(clk), .rst_n(rst_n),
    .a(a_iq),
    .b(b_iq),
    .c(c_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
