// r09 -- unbalanced_mult_pipe  (HAND-RETIMED REFERENCE)
//
// Split the multiply by operand halves and move the partial-product summation
// across the stage-1/stage-2 boundary:
//
//     a*b  ==  (a * b[15:8]) << 8  +  (a * b[7:0])
//
// Stage 1 now forms the two narrow partial products; stage 2 sums and shifts
// them and does the original add.  Three register stages before, three after --
// strict retiming, identical I/O latency.
//
// Note the stage-1 register got *wider* (two 24-bit partial products instead of
// one 32-bit product).  Retiming trading registers for period is expected and
// legal; it is why register count alone is a bad proxy for retiming quality.

module r09_unbalanced_mult_pipe_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] a,
    input  logic [15:0] b,
    input  logic [31:0] c,
    output logic [31:0] dout
);

  logic [23:0] pp_hi_q, pp_lo_q;
  logic [31:0] s2_q, s3_q;

  // Stage 1: two 16x8 partial products -- roughly half the depth of a 16x16.
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      pp_hi_q <= 24'h0;
      pp_lo_q <= 24'h0;
    end else begin
      pp_hi_q <= a * b[15:8];
      pp_lo_q <= a * b[7:0];
    end
  end

  // Stage 2: recombine the partial products, then the original add.
  always_ff @(posedge clk) begin
    if (!rst_n) s2_q <= 32'h0;
    else        s2_q <= ({8'h0, pp_hi_q} << 8) + {8'h0, pp_lo_q} + c;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) s3_q <= 32'h0;
    else        s3_q <= s2_q ^ 32'hA5A5_5A5A;
  end

  assign dout = s3_q;

endmodule

