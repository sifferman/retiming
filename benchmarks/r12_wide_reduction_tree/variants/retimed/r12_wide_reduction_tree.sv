// r12 -- wide_reduction_tree  (HAND-RETIMED REFERENCE)
//
//   din[63:0] --[ 4 x 16-input subtrees ]--> (p_q[0..3]) --[ 3-level combine + xor ]--> (out_q)
//
// The register cut moved from the root of the tree into its interior: four partial
// counts are registered instead of one total. Stage 1 is now a 16-input reduction
// (~4 levels) and stage 2 finishes the job. Two register stages before and after,
// identical latency.
//
// Register count grows from 16 to 64 bits in stage 1 -- retiming buying period with
// area, as usual. Reset values are plain zero here: four partial counts of zero sum
// to zero, which is exactly what the original's stage-2 register latched from
// sum_q's zero reset, so no pre-image is needed.
//
// SIZING NOTE -- why din is 64 bits.
//
// The first version took a 16-bit input and derived 64 summands as
// summand(x,i) = x[7:0] ^ x[15:8] ^ const_i. Every summand is therefore the SAME
// value xored with a different constant, so the sum collapses to a linear function
// of 8 variables. Measured on nangate45: 23 cells, 10 flops, 0.087 ns critical
// path -- there was no reduction tree at all, and the benchmark had been measuring
// a trivial design on both PDKs.
//
// scripts/check_equiv.py did not catch it: the output still varied, so it was
// reducible rather than constant, and the vacuity check only rejects constants.
// What exposed it was the nangate45 period calibration, where an 0.087 ns path
// stood out as impossible for a 64-input popcount.
//
// With 64 independent primary inputs the popcount is a genuine ~6-level adder tree
// and cannot be reduced away.

module r12_wide_reduction_tree_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [63:0] din,
    output logic [15:0] dout
);

  localparam logic [15:0] K = 16'h5A5A;

  // Population count over 64 INDEPENDENT bits: a real ~6-level adder tree.
  function automatic logic [15:0] popcnt (input logic [63:0] w,
                                          input int lo, input int hi);
    logic [6:0] s;
    s = '0;
    for (int i = lo; i <= hi; i++) s += 7'(w[i]);
    popcnt = {9'b0, s};
  endfunction

  logic [15:0] p_q [4];
  logic [15:0] out_q;

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      // Unpacked arrays need an explicit loop: iverilog rejects `p_q <= '0`.
      for (int j = 0; j < 4; j++) p_q[j] <= 16'h0;
    end else begin
      p_q[0] <= popcnt(din,  0, 15);
      p_q[1] <= popcnt(din, 16, 31);
      p_q[2] <= popcnt(din, 32, 47);
      p_q[3] <= popcnt(din, 48, 63);
    end
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0;
    else        out_q <= ((p_q[0] + p_q[1]) + (p_q[2] + p_q[3])) ^ K;
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r12_wide_reduction_tree_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r12_wide_reduction_tree (
    input  logic clk,
    input  logic rst_n,
    input  logic [63:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [63:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r12_wide_reduction_tree_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
