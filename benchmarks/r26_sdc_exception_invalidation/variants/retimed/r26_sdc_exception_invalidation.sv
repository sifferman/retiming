// r26 -- sdc_exception_invalidation  (HAND-RETIMED REFERENCE)
//
//   din --[ f1a: 5 rounds ]--> (mq) --[ f1b+f2b: 6 rounds ]--> (fq2) --> PO
//
// The eleven rounds are recut 5 / 6 instead of 3 / 8, so the design no longer
// needs a multicycle exception at all -- and the accompanying `override.sdc`
// removes it rather than leaving a dead constraint in the file.
//
// That is the honest fix for this class of problem: if retiming changes the stage
// boundaries, the constraints describing those boundaries have to change with
// them.  A retiming tool that rewrites the netlist without rewriting the
// exceptions has left the design in a state the designer did not sign off on.
//
// Reset: dout is fq2 in both variants and resets to zero, and the intermediate
// register's reset value is derived as the pre-image that reproduces the
// original's post-reset output -- same construction as the other Class A/C
// references.

module r26_sdc_exception_invalidation_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;
  localparam logic [15:0] K7 = 16'hB7E1, C7 = 16'h51ED;
  localparam logic [15:0] K8 = 16'h2545, C8 = 16'hF491;
  localparam logic [15:0] K9 = 16'h85EB, C9 = 16'hCA6B;
  localparam logic [15:0] KA = 16'hC2B2, CA = 16'hAE35;
  localparam logic [15:0] KB = 16'h27D4, CB = 16'hEB2F;

  // New cut: 5 rounds before the register, 6 after.
  function automatic logic [15:0] g1 (input logic [15:0] x);
    g1 = rnd(rnd(rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3), K4, C4), K5, C5);
  endfunction
  function automatic logic [15:0] g2 (input logic [15:0] x);
    g2 = rnd(rnd(rnd(rnd(rnd(rnd(x, K6, C6), K7, C7), K8, C8), K9, C9),
                 KA, CA), KB, CB);
  endfunction
  function automatic logic [15:0] g2_inv (input logic [15:0] y);
    g2_inv = rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(
               y, KB, CB), KA, CA), K9, C9), K8, C8), K7, C7), K6, C6);
  endfunction

  // The original's stage 2 latches f2(fq1) with fq1 still zero on the first
  // post-reset cycle.  Reproducing that after the recut requires the pre-image.
  function automatic logic [15:0] f2_of_zero ();
    f2_of_zero = rnd(rnd(rnd(rnd(rnd(rnd(rnd(rnd(
                   16'h0, K4, C4), K5, C5), K6, C6), K7, C7), K8, C8),
                   K9, C9), KA, CA), KB, CB);
  endfunction

  localparam logic [15:0] MQ_RESET = g2_inv(f2_of_zero());

  logic [15:0] mq, fq2;

  always_ff @(posedge clk) begin
    if (!rst_n) mq <= MQ_RESET;
    else        mq <= g1(din);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) fq2 <= 16'h0;
    else        fq2 <= g2(mq);
  end

  assign dout = fq2;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r26_sdc_exception_invalidation_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r26_sdc_exception_invalidation (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r26_sdc_exception_invalidation_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
