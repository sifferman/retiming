// r26 -- sdc_exception_invalidation  (ORIGINAL)  [DIAGNOSTIC BENCHMARK]
//
//   din --[ f1: 3 rounds ]--> (fq1) --[ f2: 8 rounds ]--> (fq2) --> PO
//                              ^^^^^                      ^^^^^
//                   the SDC declares a 2-cycle multicycle path between these two
//
// Stage 2 is deliberately too deep for one cycle.  The designer's intent is
// expressed in the constraints, not the RTL: `set_multicycle_path 2` from fq1 to
// fq2 gives that stage two cycles, which is a completely ordinary thing to do.
//
// The exception is written the only way it can be written -- by object name:
//
//     set_multicycle_path 2 -setup -from [get_cells fq1_reg*] -to [get_cells fq2_reg*]
//
// Now let the retimer loose.  It relocates the stage boundary and renames the
// registers as it does so (Genus names retimed registers `retime_*`).  The names
// `fq1_reg*` and `fq2_reg*` no longer exist, the exception matches nothing, and
// the two cycles of relief vanish -- while the tool reports a design that looks
// constrained and closed.
//
// This is measured as a diagnostic, not as Fmax: the question is whether the
// exception still binds after retiming.  It is also a concrete reason engineers
// end up fighting retimers even when the transform itself is correct.

module r26_sdc_exception_invalidation_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;
  localparam logic [15:0] K7 = 16'hB7E1, C7 = 16'h51ED;
  localparam logic [15:0] K8 = 16'h2545, C8 = 16'hF491;
  localparam logic [15:0] K9 = 16'h85EB, C9 = 16'hCA6B;
  localparam logic [15:0] KA = 16'hC2B2, CA = 16'hAE35;
  localparam logic [15:0] KB = 16'h27D4, CB = 16'hEB2F;

  function automatic logic [15:0] f1 (input logic [15:0] x);
    f1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction

  // Eight rounds: too deep for one cycle at the target period, which is why the
  // multicycle exception exists.
  function automatic logic [15:0] f2 (input logic [15:0] x);
    f2 = rnd(rnd(rnd(rnd(rnd(rnd(rnd(rnd(
           x, K4, C4), K5, C5), K6, C6), K7, C7), K8, C8), K9, C9), KA, CA), KB, CB);
  endfunction

  logic [15:0] fq1, fq2;

  always_ff @(posedge clk) begin
    if (!rst_n) fq1 <= 16'h0;
    else        fq1 <= f1(din);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) fq2 <= 16'h0;
    else        fq2 <= f2(fq1);
  end

  assign dout = fq2;

endmodule

