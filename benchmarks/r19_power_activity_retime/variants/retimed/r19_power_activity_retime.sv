// r19 -- power_activity_retime  (HAND-RETIMED REFERENCE)
//
//   din[63:0] --[ xor mask ]--[ popcount tree ]--> (narrow_q : 8 FF) --> (out_q : 8 FF)
//
// The register cut moved forward across the reduction. Two register stages before,
// two after; identical I/O latency; cycle-for-cycle identical outputs.
//
// 64 wide, high-activity flip-flops become 8 narrow ones holding a population
// count -- a value that changes far less often than the raw data, since it only
// moves when the number of set bits changes. Sequential switched capacitance drops
// by 8x in register count and considerably more in activity, at the cost of one
// extra logic level in stage 1.
//
// Reset value
// -----------
// The original forces out_q to zero during reset, but on the first cycle after
// release it latches reduce(wide_q_reset) = reduce(0). After the move that same
// cycle reads narrow_q, so narrow_q must reset to reduce(0) -- not to zero. A wrong
// value here produces a one-cycle mismatch after every reset, which is exactly
// what the testbench's mid-run reset pulse is for.

module r19_power_activity_retime_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [63:0] din,
    output logic [7:0]  dout
);

  localparam logic [63:0] MASK = 64'hA5A5_1234_7B15_9E37;

  function automatic logic [7:0] reduce (input logic [63:0] w);
    logic [6:0] s;
    s = '0;
    for (int i = 0; i < 64; i++) s += 7'(w[i]);
    reduce = {1'b0, s} ^ 8'h11;
  endfunction

  // Derived, not guessed: the value the original's second stage latches from the
  // reset state of the first.
  localparam logic [7:0] NARROW_RESET = reduce(64'h0);

  logic [7:0] narrow_q;
  logic [7:0] out_q;

  // Stage 1 now spans the mask and the whole reduction, and holds 8 quiet bits.
  always_ff @(posedge clk) begin
    if (!rst_n) narrow_q <= NARROW_RESET;
    else        narrow_q <= reduce(din ^ MASK);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 8'h0;
    else        out_q <= narrow_q;
  end

  assign dout = out_q;

endmodule

