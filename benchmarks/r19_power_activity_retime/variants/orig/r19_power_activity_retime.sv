// r19 -- power_activity_retime  (ORIGINAL)
//
//   din[63:0] --[ xor mask ]--> (wide_q : 64 FF) --[ popcount tree ]--> (out_q : 8 FF)
//
// The register cut sits on the WIDE, HIGH-ACTIVITY side of the reduction: 64
// flip-flops toggling at the input data rate, all feeding a 6-level adder tree.
//
// Moving the cut past the reduction is a legal, latency-preserving retiming that
// replaces 64 busy flops with 8 quiet ones. It costs one extra logic level in
// stage 1 and saves a large amount of switched capacitance.
//
// Monteiro, Devadas and Ghosh (ICCAD 1993) is the reference for the underlying
// observation: activity at a flop's output is lower than at its input, so where
// the register sits changes switched capacitance even at constant timing. No
// production synthesis tool optimises for this.
//
// NOTE ON SIZING -- this is why `din` is 64 bits wide.
// The first version of this benchmark took a 16-bit input and expanded it to 64
// bits by xor-ing four rotations with four constants. That expansion is affine, so
// the "64-input popcount" collapsed algebraically to a weighted sum of just 16
// variables with small even coefficients, and Genus implemented the entire retimed
// stage in 32 cells. The reduction tree the benchmark claimed to have did not
// exist. With 64 independent primary inputs the popcount is genuinely a 6-level
// tree over 64 unrelated bits and cannot be reduced away.

module r19_power_activity_retime_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [63:0] din,
    output logic [7:0]  dout
);

  localparam logic [63:0] MASK = 64'hA5A5_1234_7B15_9E37;

  // Population count of 64 independent bits: roughly six levels of adder tree.
  function automatic logic [7:0] reduce (input logic [63:0] w);
    logic [6:0] s;
    s = '0;
    for (int i = 0; i < 64; i++) s += 7'(w[i]);
    reduce = {1'b0, s} ^ 8'h11;
  endfunction

  logic [63:0] wide_q;
  logic [7:0]  out_q;

  // 64 flops on the busy side of the tree.
  always_ff @(posedge clk) begin
    if (!rst_n) wide_q <= 64'h0;
    else        wide_q <= din ^ MASK;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 8'h0;
    else        out_q <= reduce(wide_q);
  end

  assign dout = out_q;

endmodule

