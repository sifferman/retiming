// r10 -- long_carry_chain  (DIRECTIVE VARIANT)
//
//   {a,b,c,d,e} --[ ((a+b)+(c+d))+e : three 32-bit carry levels ]--> (r1) --[ xor ]--> (r2)
//
// All three adder levels sit in stage 1; stage 2 does a single xor.  Each level
// is a full 32-bit carry propagation, so stage 1 is roughly three carry chains
// deep and stage 2 is essentially free.

module r10_long_carry_chain_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [31:0] a,
    input  logic [31:0] b,
    input  logic [31:0] c,
    input  logic [31:0] d,
    input  logic [31:0] e,
    output logic [31:0] dout
);

  localparam logic [31:0] K = 32'hA5A5_5A5A;

  logic [31:0] r1, r2;

  always_ff @(posedge clk) begin
    if (!rst_n) r1 <= 32'h0;
    else        r1 <= ((a + b) + (c + d)) + e;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r2 <= 32'h0;
    else        r2 <= r1 ^ K;
  end

  assign dout = r2;

endmodule

