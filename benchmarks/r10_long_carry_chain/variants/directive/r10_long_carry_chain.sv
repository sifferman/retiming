  logic [31:0] a_sr, a_word;
  logic [1:0] a_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      a_sr <= '0; a_word <= '0; a_cnt <= '0;
    end else begin
      a_sr  <= {a_sr[23:0], a_iq};
      a_cnt <= (a_cnt == 3) ? '0 : a_cnt + 1'b1;
