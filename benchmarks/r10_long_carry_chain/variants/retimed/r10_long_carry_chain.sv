// r10 -- long_carry_chain  (HAND-RETIMED REFERENCE)
//
//   {a,b,c,d} --[ (a+b)+(c+d) : two levels ]--> (p) --+
//   e ----------------------------------------> (e_q) +--[ +, xor : one level ]--> (r2)
//
// The final adder moved from stage 1 into stage 2, leaving two carry levels
// before the register and one after.  Two register stages before, two after,
// identical latency.
//
// The instructive cost
// --------------------
// Moving a register backward across `+ e` splits an operator whose second operand
// arrives from outside the moved cone.  For the retimed circuit to see the same
// `e` that the original saw, `e` must be delayed by one cycle -- so the transform
// buys a shorter period at the price of a 32-bit register.
//
// This is why register count is a bad proxy for retiming quality, and why a
// retimer whose objective includes minimum registers will decline this move even
// though it is delay-optimal.

module r10_long_carry_chain_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [31:0] a,
    input  logic [31:0] b,
    input  logic [31:0] c,
    input  logic [31:0] d,
    input  logic [31:0] e,
    output logic [31:0] dout
);

  localparam logic [31:0] K = 32'hA5A5_5A5A;

  logic [31:0] p, e_q, r2;

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      p   <= 32'h0;
      e_q <= 32'h0;      // the price of the move
    end else begin
      p   <= (a + b) + (c + d);
      e_q <= e;
    end
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r2 <= 32'h0;
    else        r2 <= (p + e_q) ^ K;
  end

  assign dout = r2;

endmodule

