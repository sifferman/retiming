// r28 -- congestion_wire_split  (DIRECTIVE VARIANT)
//
//   (in_q) -[1 level]-> (mid_q) ==== 256-bit crossing ====> [2 levels] -> (out_q)
//
// Targets the regime the project cares about: NET delay comparable to or larger
// than LOGIC delay. Two things make that reachable:
//
//  * SHALLOW LOGIC -- one gate level per stage. It is the wire/logic RATIO that
//    has to be attacked, not the absolute wire delay.
//  * A TECHNOLOGY WHERE WIRES COST SOMETHING -- nangate45 metal1 R*C is
//    4.0e-4 ps/um^2 against gf180's 5.2e-8, i.e. 7710x more per unit length, so a
//    wire costs a gate-delay at ~700 um instead of ~62 mm.
//
// A retimer that models wires as zero delay sees stage 2 (two levels) as the
// longer one and has no reason to move the register back. With the crossing
// costing W the real stage delays are a and W + b, so the correct cut is
// asymmetric -- see the reference.

module r28_congestion_wire_split_core (
    input  logic         clk,
    input  logic         rst_n,
    input  logic [255:0] din,
    output logic [255:0] dout
);
  // Replication counts written out (32 = W/8): iverilog rejects a signed `int`
  // expression as a replication count ("indefinite width").
  localparam logic [255:0] MASK_A = {32{8'hA5}};
  localparam logic [255:0] MASK_C = {32{8'h3C}};
  localparam logic [255:0] MID_RESET_ORIG = {32{8'h5A}};

  localparam int W = 256;   // wide bus -- the crossing is a real bundle

  // ONE gate level per stage, and each level must be DATA-DEPENDENT.
  //
  // This is the whole point of the benchmark, and two earlier attempts got it
  // wrong in opposite directions:
  //   * 8 rounds of 16-bit arithmetic gave 5.884 ns of cell delay against
  //     0.031 ns of interconnect -- a 0.5% route share no routing cap could shift.
  //   * Replacing it with AND/OR masks collapsed to a constant, because
  //     (x & M) | M == M. scripts/check_equiv.py caught it: 3 distinct outputs in
  //     2001 cycles.
  // XOR-based levels are one gate per bit AND non-degenerate.
  function automatic logic [W-1:0] lvl_a (input logic [W-1:0] x);
    lvl_a = x ^ MASK_A;                              // 1 XOR per bit
  endfunction
  function automatic logic [W-1:0] lvl_b (input logic [W-1:0] x);
    lvl_b = x ^ {x[W-2:0], x[W-1]};                  // 1 XOR per bit, mixes bits
  endfunction
  function automatic logic [W-1:0] lvl_c (input logic [W-1:0] x);
    lvl_c = x ^ MASK_C;                              // 1 XOR per bit
  endfunction

  logic [W-1:0] in_q, mid_q, out_q;
  logic [W-1:0] bus;

  always_ff @(posedge clk) begin
    if (!rst_n) in_q <= '0;
    else        in_q <= din;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) mid_q <= MID_RESET_ORIG;
    else        mid_q <= lvl_a(in_q);
  end

  // THE CROSSING. Pure wire: 256 bits from cluster A to cluster B.
  always_comb bus = mid_q;

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= '0;
    else        out_q <= lvl_c(lvl_b(bus));
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r28_congestion_wire_split_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r28_congestion_wire_split (
    input  logic clk,
    input  logic rst_n,
    input  logic [7:0] din,
    output logic [7:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [7:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [255:0] dout_c;
  logic [255:0] din_sr, din_word;
  logic [4:0] din_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_sr <= '0; din_word <= '0; din_cnt <= '0;
    end else begin
      din_sr  <= {din_sr[247:0], din_iq};
      din_cnt <= (din_cnt == 31) ? '0 : din_cnt + 1'b1;
      // word complete on the last beat: latch it, hold it stable
      if (din_cnt == 31)
        din_word <= {din_sr[247:0], din_iq};
    end
  end
  logic [255:0] dout_sr;
  logic [4:0] dout_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin dout_sr <= '0; dout_cnt <= '0; end
    else begin
      dout_cnt <= (dout_cnt == 31) ? '0 : dout_cnt + 1'b1;
      dout_sr  <= (dout_cnt == 0) ? dout_c : {dout_sr[247:0], 8'h0};
    end
  end

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r28_congestion_wire_split_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_word),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_sr[255:248];
    end
  end

endmodule
