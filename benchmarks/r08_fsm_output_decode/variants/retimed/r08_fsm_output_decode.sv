// r08 -- fsm_output_decode  (HAND-RETIMED REFERENCE)
//
//   (state_q, din_q) --[ d1 ]--> (mid_q) --[ d2 ]--> PO
//
// out_q moved backward through d2.  One register between the FSM stage and the
// output in both versions, so latency is unchanged; the second half of the decode
// becomes a register-to-output path instead of a register-to-register one.
//
// Reset: the original drives dout = 0 while reset holds, and dout is now d2(mid_q),
// so mid_q must reset to d2^-1(0).  d2 is a composition of bijections, so that
// pre-image exists and is unique; it is derived at elaboration time.

module r08_fsm_output_decode_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [3:0]  cmd,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] d1 (input logic [15:0] x, input logic [5:0] st);
    logic [15:0] v;
    v  = x ^ {10'h0, st};
    d1 = rnd(rnd(rnd(v, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] d2 (input logic [15:0] x);
    d2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] d2_inv (input logic [15:0] y);
    d2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [5:0]  S_IDLE   = 6'b000001;
  localparam logic [15:0] MID_RESET = d2_inv(16'h0);

  logic [5:0]  state_q, state_d;
  logic [15:0] din_q, mid_q;

  always_comb begin
    unique case (1'b1)
      state_q[0]: state_d = cmd[0] ? 6'b000010 : S_IDLE;
      state_q[1]: state_d = cmd[1] ? 6'b000100 : 6'b000010;
      state_q[2]: state_d = cmd[2] ? 6'b001000 : 6'b000100;
      state_q[3]: state_d = cmd[3] ? 6'b010000 : 6'b001000;
      state_q[4]: state_d = cmd[0] ? 6'b100000 : 6'b010000;
      state_q[5]: state_d = S_IDLE;
      default:    state_d = S_IDLE;
    endcase
  end

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      state_q <= S_IDLE;
      din_q   <= 16'h0;
    end else begin
      state_q <= state_d;
      din_q   <= din;
    end
  end

  always_ff @(posedge clk) begin
    if (!rst_n) mid_q <= MID_RESET;
    else        mid_q <= d1(din_q, state_q);
  end

  assign dout = d2(mid_q);

endmodule

