// Every input is captured and every output is registered, so ALL logic in
// r08_fsm_output_decode_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r08_fsm_output_decode (
    input  logic clk,
    input  logic rst_n,
    input  logic [3:0] cmd,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [3:0] cmd_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      cmd_iq <= '0;
      din_iq <= '0;
    end else begin
      cmd_iq <= cmd;
      din_iq <= din;
    end
  end

  r08_fsm_output_decode_core u_core (
    .clk(clk), .rst_n(rst_n),
    .cmd(cmd_iq),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
