// r31 -- clone_distinct_reset  (REFERENCE = one CLONED, PRE-DECODED register per lane)
//
// Generalises r30, which is reduced from a real Vivado failure (sifferman/ternip
// 55bf227 -> 7b658c7). In r30 every registered decode happened to reset to the same
// kind of value. Here each clone needs a DIFFERENT reset constant, which is the case
// CLAUDE.md singles out: "duplicating state_q several times, and spreading it out
// across the combinational cloud, while also keeping track of the new reset value,
// while also keeping an unchanged state_q for calculating state_d".
//
// Why this should be hard for any retimer:
//   * the register is in a FEEDBACK LOOP (phase_q feeds its own next value), so the
//     loop's register count is invariant and classical retiming cannot move it;
//   * relieving the fanout needs DUPLICATION, which is not a retiming move at all;
//   * each duplicate must be given its own reset value, computed by pushing the
//     original reset state through that lane's decode -- so a tool has to solve a
//     small initial-state problem per clone (Touati & Brayton) rather than copy a
//     constant.
//
// THE TRANSFORM: give every lane its own register holding that lane's mask, decoded
// from the NEXT phase (phase_d) so it lands in step with phase_q. Three things follow:
//   * the decode leaves the critical path -- it now happens in the previous cycle;
//   * the high-fanout net becomes LANES independent register outputs, each placeable
//     next to the lane it drives, instead of one net crossing the whole die;
//   * phase_q survives untouched for its own feedback loop.
//
// And the part a tool has to get right: every clone needs a DIFFERENT reset constant,
// namely lane_mask(i, 7) for the reset phase 7. Reset them all to zero and the design
// is correct in steady state and wrong for the cycles right after every reset -- which
// is the failure mode this benchmark exists to catch, and why gen_tb.py pulses reset
// mid-run rather than only at time zero.

module r31_clone_distinct_reset_core #(
    parameter int LANES = 24,
    parameter int WIDTH = 32
) (
    input  logic         clk,
    input  logic         rst_n,
    input  logic         step,
    input  logic [31:0]  din,
    output logic [767:0] dout        // LANES*WIDTH-1:0
);
  localparam int PH = 5;             // phase counter width

  // ---- the feedback register: cannot be retimed, only duplicated -------------
  logic [PH-1:0] phase_q, phase_d;
  always_comb phase_d = step ? (phase_q + 1'b1) : phase_q;

  always_ff @(posedge clk) begin
    if (!rst_n) phase_q <= 5'd7;      // NOT zero: the reset state is arbitrary, so a
    else        phase_q <= phase_d;   // clone's reset value cannot be assumed to be 0
  end

  // Deep enough to cost real delay after the register, and different per lane so no
  // two clones can share one value.
  function automatic logic [WIDTH-1:0] lane_mask (input int i, input logic [PH-1:0] p);
    logic [WIDTH-1:0] m;
    m = WIDTH'(i * 2654435761);                 // lane-specific seed
    m = m ^ (m << 5) ^ WIDTH'(p);
    m = m ^ (m >> 3) ^ WIDTH'(p * 7 + 1);
    m = m ^ (m << 7) ^ WIDTH'(p * 13);
    lane_mask = m;
  endfunction

  logic [WIDTH-1:0] acc_q [LANES];

  for (genvar i = 0; i < LANES; i++) begin : g_lane
    // Each lane decodes the SHARED phase_q differently, so phase_q fans out to all
    // LANES lanes and every lane pays the decode delay after the register.
    // A per-lane MASK decoded from the phase alone. Being a function of phase only
    // is what makes it movable across the register; anything reading din arrives in
    // the same cycle and could not be retimed at all.
    logic [WIDTH-1:0] mask;
    always_ff @(posedge clk) begin
      // reset value = this lane's decode of the reset phase, not zero
      if (!rst_n) mask <= lane_mask(i, 5'd7);
      else        mask <= lane_mask(i, phase_d);
    end

    always_ff @(posedge clk) begin
      if (!rst_n) acc_q[i] <= WIDTH'(i);      // per-lane, non-uniform initial state
      else        acc_q[i] <= acc_q[i] ^ (din & mask);
    end
    assign dout[i*WIDTH +: WIDTH] = acc_q[i];
  end

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r31_clone_distinct_reset_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r31_clone_distinct_reset (
    input  logic clk,
    input  logic rst_n,
    input  logic step,
    input  logic [31:0] din,
    output logic [7:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic step_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [31:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [767:0] dout_c;
  logic [767:0] dout_sr;
  logic [6:0] dout_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin dout_sr <= '0; dout_cnt <= '0; end
    else begin
      dout_cnt <= (dout_cnt == 95) ? '0 : dout_cnt + 1'b1;
      dout_sr  <= (dout_cnt == 0) ? dout_c : {dout_sr[759:0], 8'h0};
    end
  end

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      step_iq <= '0;
      din_iq <= '0;
    end else begin
      step_iq <= step;
      din_iq <= din;
    end
  end

  r31_clone_distinct_reset_core u_core (
    .clk(clk), .rst_n(rst_n),
    .step(step_iq),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_sr[767:760];
    end
  end

endmodule
