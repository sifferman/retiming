// r06 -- fsm_high_fanin  (HAND-RETIMED REFERENCE)
//
//   status --[ deep reduce ]--> (red_q) --[ next_state ]--> (state_q)
//
// status_q retimed FORWARD across the reduction.  The 64-bit status register
// becomes a 4-bit reduced register, and the deep tree moves from the FSM's fanin
// cone into the input stage.
//
// Latency argument
// ----------------
// Original:  status_q[t] = status[t-1], so state_q[t+1] = f(state_q[t], reduce(status[t-1])).
// Retimed :  red_q[t]    = reduce(status[t-1]),      so state_q[t+1] = f(state_q[t], red_q[t])
//                                                                   = f(state_q[t], reduce(status[t-1])).
// Identical, cycle for cycle.  This is what "forward retiming preserves latency"
// means concretely.
//
// Reset: the original's first post-reset FSM decision uses reduce(status_q) with
// status_q still zero, i.e. reduce(0).  So red_q must reset to reduce(0), derived
// here at elaboration time rather than assumed to be zero -- and reduce(0) is in
// fact 4'b0000, but deriving it keeps the reference honest if the thresholds
// change.
//
// Bonus: this also shrinks the register count from 64 bits to 4.

module r06_fsm_high_fanin_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [63:0] status,
    output logic [5:0]  dout
);

  localparam logic [5:0] S_IDLE = 6'b000001;
  localparam logic [5:0] S_A    = 6'b000010;
  localparam logic [5:0] S_B    = 6'b000100;
  localparam logic [5:0] S_C    = 6'b001000;
  localparam logic [5:0] S_D    = 6'b010000;
  localparam logic [5:0] S_E    = 6'b100000;

  function automatic logic [3:0] reduce (input logic [63:0] s);
    logic [9:0] acc;
    acc = '0;
    for (int i = 0; i < 64; i++) acc += 10'(s[i] ? (i + 1) : 0);
    reduce = {acc > 10'd520, acc > 10'd340, acc > 10'd180, acc > 10'd60};
  endfunction

  localparam logic [3:0] RED_RESET = reduce(64'h0);

  logic [3:0] red_q;
  logic [5:0] state_q, state_d;

  // Reduction now sits BEFORE the register.
  always_ff @(posedge clk) begin
    if (!rst_n) red_q <= RED_RESET;
    else        red_q <= reduce(status);
  end

  always_comb begin
    unique case (1'b1)
      state_q[0]: state_d = red_q[0] ? S_A : S_IDLE;
      state_q[1]: state_d = red_q[1] ? S_B : S_A;
      state_q[2]: state_d = red_q[2] ? S_C : S_B;
      state_q[3]: state_d = red_q[3] ? S_D : S_C;
      state_q[4]: state_d = red_q[0] ? S_E : S_D;
      state_q[5]: state_d = S_IDLE;
      default:    state_d = S_IDLE;
    endcase
  end

  always_ff @(posedge clk) begin
    if (!rst_n) state_q <= S_IDLE;
    else        state_q <= state_d;
  end

  assign dout = state_q;

endmodule

