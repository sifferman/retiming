// r06 -- fsm_high_fanin  (DIRECTIVE VARIANT)
//
//   status --> (status_q) --[ deep reduce ]--[ next_state ]--> (state_q)
//                                                  ^              |
//                                                  +--------------+
//
// The critical path is status_q -> reduce -> next_state -> state_q.  The FSM loop
// itself (state_q -> next_state -> state_q) is short and nowhere near critical;
// all the depth is in the reduction that feeds it.
//
// The fix is a textbook FORWARD retiming: move status_q across the reduction so
// that the reduce happens before the register rather than after it.  Latency is
// preserved exactly, because a register moved forward past a function still
// delivers that function's value one cycle later -- see the reference for the
// cycle-by-cycle argument.
//
// What makes it a stressor: the register's destination is FSM next-state logic.
// Tools protect state machines -- Genus has retime_preserve_state_points, and
// FSM extraction generally treats the state register and its immediate fanin as
// something not to be disturbed.

module r06_fsm_high_fanin_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [63:0] status,
    output logic [5:0]  dout
);

  localparam logic [5:0] S_IDLE = 6'b000001;
  localparam logic [5:0] S_A    = 6'b000010;
  localparam logic [5:0] S_B    = 6'b000100;
  localparam logic [5:0] S_C    = 6'b001000;
  localparam logic [5:0] S_D    = 6'b010000;
  localparam logic [5:0] S_E    = 6'b100000;

  // Deep reduction over all 64 status bits: weighted popcount plus a compare.
  function automatic logic [3:0] reduce (input logic [63:0] s);
    logic [9:0] acc;
    acc = '0;
    for (int i = 0; i < 64; i++) acc += 10'(s[i] ? (i + 1) : 0);
    reduce = {acc > 10'd520, acc > 10'd340, acc > 10'd180, acc > 10'd60};
  endfunction

  logic [63:0] status_q;
  logic [5:0]  state_q, state_d;
  logic [3:0]  red;

  always_ff @(posedge clk) begin
    if (!rst_n) status_q <= 64'h0;
    else        status_q <= status;
  end

  // Reduction sits AFTER the register -- this is the problem.
  always_comb red = reduce(status_q);

  always_comb begin
    unique case (1'b1)
      state_q[0]: state_d = red[0] ? S_A    : S_IDLE;
      state_q[1]: state_d = red[1] ? S_B    : S_A;
      state_q[2]: state_d = red[2] ? S_C    : S_B;
      state_q[3]: state_d = red[3] ? S_D    : S_C;
      state_q[4]: state_d = red[0] ? S_E    : S_D;
      state_q[5]: state_d = S_IDLE;
      default:    state_d = S_IDLE;
    endcase
  end

  always_ff @(posedge clk) begin
    if (!rst_n) state_q <= S_IDLE;
    else        state_q <= state_d;
  end

  assign dout = state_q;

endmodule

