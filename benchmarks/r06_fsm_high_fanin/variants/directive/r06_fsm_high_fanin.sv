// r06_fsm_high_fanin_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r06_fsm_high_fanin (
    input  logic clk,
    input  logic rst_n,
    input  logic [63:0] status,
    output logic [5:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [63:0] status_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [5:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      status_iq <= '0;
    end else begin
      status_iq <= status;
    end
  end

  r06_fsm_high_fanin_core u_core (
    .clk(clk), .rst_n(rst_n),
    .status(status_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
