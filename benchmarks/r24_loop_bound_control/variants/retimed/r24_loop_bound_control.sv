// r24 -- loop_bound_control  (REFERENCE = NO CHANGE)  [NEGATIVE CONTROL]
//
// There is no legal retiming of this circuit that reduces its clock period, so
// the reference solution IS the original, unmodified.
//
// Leiserson-Saxe bound the minimum achievable period below by
// max over cycles of (cycle delay / registers in cycle); here that is
// delay(8 rounds) / 1, and no choice of retiming lags changes it.
//
// This file is intentionally behaviourally identical to variants/orig.  Any
// measured difference between the two is run-to-run tool noise, and that noise
// floor is what the other benchmarks' reported gains must clear.

module r24_loop_bound_control_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  logic [15:0] acc_q;

  always_ff @(posedge clk) begin
    if (!rst_n) acc_q <= 16'h1234;
    else begin
      acc_q <= rnd(rnd(rnd(rnd(rnd(rnd(rnd(rnd(
                 acc_q ^ din, 16'h9E37, 16'h1234), 16'h7B15, 16'h5A5A),
                 16'hC2B2, 16'h0F1E), 16'h27D4, 16'hBEEF), 16'h1656, 16'h3C3C),
                 16'h6763, 16'h07E1), 16'hB7E1, 16'h51ED), 16'h2545, 16'hF491);
    end
  end

  assign dout = acc_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r24_loop_bound_control_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r24_loop_bound_control (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r24_loop_bound_control_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
