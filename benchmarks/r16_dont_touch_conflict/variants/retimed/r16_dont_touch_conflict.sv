// r16 -- dont_touch_conflict  (HAND-RETIMED REFERENCE)
//
//   din -> (r_in) --[ a: 2 ]--> (r_pinned) --[ b1: 4 ]--> (r_mid) --[ b2: 2 ]--> PO
//                                ^^^^^^^^^^ still pinned, still exactly where it was
//
// r_pinned is untouched, honouring the constraint.  The output register moved
// backward two rounds, so the worst stage drops from six rounds to four.
//
// This is deliberately NOT the unconstrained optimum -- with r_pinned free, the
// eight rounds could be spread evenly across three stages at under three rounds
// each.  The reference is the best solution that respects the pin, which is the
// right target for a tool to hit.
//
// Reset: dout was r_out (reset 0) and is now b2(r_mid), so r_mid resets to
// b2^-1(0), derived at elaboration time.

module r16_dont_touch_conflict_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] KA1 = 16'h9E37, CA1 = 16'h1234;
  localparam logic [15:0] KA2 = 16'h7B15, CA2 = 16'h5A5A;
  localparam logic [15:0] KB1 = 16'hC2B2, CB1 = 16'h0F1E;
  localparam logic [15:0] KB2 = 16'h27D4, CB2 = 16'hBEEF;
  localparam logic [15:0] KB3 = 16'h1656, CB3 = 16'h3C3C;
  localparam logic [15:0] KB4 = 16'h6763, CB4 = 16'h07E1;
  localparam logic [15:0] KB5 = 16'hB7E1, CB5 = 16'h51ED;
  localparam logic [15:0] KB6 = 16'h2545, CB6 = 16'hF491;

  function automatic logic [15:0] a_fn (input logic [15:0] x);
    a_fn = rnd(rnd(x, KA1, CA1), KA2, CA2);
  endfunction
  function automatic logic [15:0] b1 (input logic [15:0] x);
    b1 = rnd(rnd(rnd(rnd(x, KB1, CB1), KB2, CB2), KB3, CB3), KB4, CB4);
  endfunction
  function automatic logic [15:0] b2 (input logic [15:0] x);
    b2 = rnd(rnd(x, KB5, CB5), KB6, CB6);
  endfunction
  function automatic logic [15:0] b2_inv (input logic [15:0] y);
    b2_inv = rnd_inv(rnd_inv(y, KB6, CB6), KB5, CB5);
  endfunction

  localparam logic [15:0] MID_RESET = b2_inv(16'h0);

  logic [15:0] r_in, r_mid;
  (* dont_touch = "yes" *) (* preserve = "true" *) (* syn_preserve = "1" *)
  logic [15:0] r_pinned;

  always_ff @(posedge clk) begin
    if (!rst_n) r_in <= 16'h0;
    else        r_in <= din;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r_pinned <= 16'h0;
    else        r_pinned <= a_fn(r_in);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r_mid <= MID_RESET;
    else        r_mid <= b1(r_pinned);
  end

  assign dout = b2(r_mid);

endmodule

