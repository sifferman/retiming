// r16 -- dont_touch_conflict  (ORIGINAL)
//
//   din -> (r_in) --[ a: 2 rounds ]--> (r_pinned) --[ b: 6 rounds ]--> (r_out) -> PO
//                                       ^^^^^^^^^^ dont_touch / preserve
//
// Stage 2 is two rounds, stage 3 is six.  The obvious fix -- push r_pinned forward
// into b -- is forbidden: that register is marked preserve, as one might mark a
// register that is observed by an external checker, feeds a scan-visible point, or
// is part of a signed-off interface.
//
// The pin does NOT make the design unimprovable.  r_out is still movable, and
// pulling it backward into b recovers most of the loss.  The point of the
// benchmark is graceful degradation: does the retimer work around an immovable
// register, or does it abandon the whole design?

module r16_dont_touch_conflict_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] KA1 = 16'h9E37, CA1 = 16'h1234;
  localparam logic [15:0] KA2 = 16'h7B15, CA2 = 16'h5A5A;
  localparam logic [15:0] KB1 = 16'hC2B2, CB1 = 16'h0F1E;
  localparam logic [15:0] KB2 = 16'h27D4, CB2 = 16'hBEEF;
  localparam logic [15:0] KB3 = 16'h1656, CB3 = 16'h3C3C;
  localparam logic [15:0] KB4 = 16'h6763, CB4 = 16'h07E1;
  localparam logic [15:0] KB5 = 16'hB7E1, CB5 = 16'h51ED;
  localparam logic [15:0] KB6 = 16'h2545, CB6 = 16'hF491;

  function automatic logic [15:0] a_fn (input logic [15:0] x);
    a_fn = rnd(rnd(x, KA1, CA1), KA2, CA2);
  endfunction
  // b split as b1 (4 rounds) then b2 (2 rounds); the reference cuts between them.
  function automatic logic [15:0] b1 (input logic [15:0] x);
    b1 = rnd(rnd(rnd(rnd(x, KB1, CB1), KB2, CB2), KB3, CB3), KB4, CB4);
  endfunction
  function automatic logic [15:0] b2 (input logic [15:0] x);
    b2 = rnd(rnd(x, KB5, CB5), KB6, CB6);
  endfunction

  logic [15:0] r_in, r_out;
  (* dont_touch = "yes" *) (* preserve = "true" *) (* syn_preserve = "1" *)
  logic [15:0] r_pinned;

  always_ff @(posedge clk) begin
    if (!rst_n) r_in <= 16'h0;
    else        r_in <= din;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r_pinned <= 16'h0;
    else        r_pinned <= a_fn(r_in);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r_out <= 16'h0;
    else        r_out <= b2(b1(r_pinned));
  end

  assign dout = r_out;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r16_dont_touch_conflict_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r16_dont_touch_conflict (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r16_dont_touch_conflict_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
