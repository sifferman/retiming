// r18 -- clock_gated_region  (DIRECTIVE VARIANT)
//
//   din --[ 6 rounds ]--> (s1_q,en) --[ 1 round ]--> (s2_q,en) --[ 1 round ]--> (s3_q,en)
//
// A three-stage pipeline sharing one enable.  The flow inserts a clock gate for
// the region (see common.tcl), so all three stages hang off one ICG.
//
// The logic is badly unbalanced: six rounds in front of the first register, one
// each in front of the other two.  Rebalancing is a plain retiming, but it moves
// registers *inside* the clock-gated domain, which changes how many flops the ICG
// drives and how the enable fans out.
//
// The structural point: clock-gating insertion and retiming are separate passes.
// Whichever runs second treats the other's decisions as fixed, so the combined
// result is order-dependent rather than jointly optimised.

module r18_clock_gated_region_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic        en,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;
  localparam logic [15:0] K7 = 16'hB7E1, C7 = 16'h51ED;
  localparam logic [15:0] K8 = 16'h2545, C8 = 16'hF491;

  logic [15:0] s1_q, s2_q, s3_q;

  // All six rounds in stage 1.
  always_ff @(posedge clk) begin
    if (!rst_n)  s1_q <= 16'h0;
    else if (en) s1_q <= rnd(rnd(rnd(rnd(rnd(rnd(din, K1, C1), K2, C2), K3, C3),
                                     K4, C4), K5, C5), K6, C6);
  end

  always_ff @(posedge clk) begin
    if (!rst_n)  s2_q <= 16'h0;
    else if (en) s2_q <= rnd(s1_q, K7, C7);
  end

  always_ff @(posedge clk) begin
    if (!rst_n)  s3_q <= 16'h0;
    else if (en) s3_q <= rnd(s2_q, K8, C8);
  end

  assign dout = s3_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r18_clock_gated_region_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r18_clock_gated_region (
    input  logic clk,
    input  logic rst_n,
    input  logic en,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic en_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      en_iq <= '0;
      din_iq <= '0;
    end else begin
      en_iq <= en;
      din_iq <= din;
    end
  end

  r18_clock_gated_region_core u_core (
    .clk(clk), .rst_n(rst_n),
    .en(en_iq),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
