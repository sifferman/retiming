// r32 -- backward_reset_preimage  (ORIGINAL = badly placed register, 8 levels / 2)
//
// The one mechanism in retiming theory this suite had no benchmark for: BACKWARD
// retiming whose required initial state DOES NOT EXIST.
//
// Moving a register forward is easy -- the new register's reset value is the old one
// pushed through the logic that moved behind it. Moving one BACKWARD needs the
// opposite: a value x with f(x) = v, where v was the old reset value. If f is not
// surjective and v is outside its image, NO SUCH x EXISTS. This is the initial-state
// (pre-image) problem from Touati & Brayton, and it is the reason Genus ships
// retime_optimize_reset defaulting to FALSE and retime_fallback_to_explicit_reset
// defaulting to TRUE: rather than solve it, the tool either declines to move the
// register or bolts explicit reset multiplexers onto the moved one.
//
//   in_q --[A: 2 levels]--[B: 6 levels]--> (mid_q) --[C: 2 levels]--> out_q
//                                          ^^^^^^
//   8 levels into mid_q, 2 levels out of it. Balancing needs mid_q moved BACKWARD by
//   three levels, to 5/5. And the three levels it must cross include an AND-mask,
//   which forces bits to zero and so is NOT surjective -- while mid_q's reset value
//   has ones in exactly those positions. The pre-image is empty by construction.

module r32_backward_reset_preimage_core (
    input  logic          clk,
    input  logic          rst_n,
    input  logic [255:0]  din,
    output logic [255:0]  dout
);
  localparam int W = 256;

  // The non-surjective step: bits selected by ZERO_MASK can never be 1 at its output.
  localparam logic [W-1:0] ZERO_MASK = {32{8'hF0}};

  // mid_q's reset value deliberately has ones in the positions ZERO_MASK clears, so
  // no value entering the mask can produce it. A tool that wants to move mid_q back
  // across the mask must add explicit reset logic; it cannot pick a constant.
  localparam logic [W-1:0] MID_RESET = {32{8'h0F}} | {32{8'h50}};

  function automatic logic [W-1:0] rot (input logic [W-1:0] x, input int n);
    rot = (x << n) | (x >> (W - n));
  endfunction

  // ---- A: 2 levels ----------------------------------------------------------
  function automatic logic [W-1:0] stage_a (input logic [W-1:0] x);
    stage_a = (x ^ rot(x, 3)) ^ (x & rot(x, 7));
  endfunction

  // ---- B: 6 levels, the last three of which are what a backward move must cross --
  function automatic logic [W-1:0] b_head (input logic [W-1:0] x);   // 3 levels
    logic [W-1:0] t;
    t = x ^ rot(x, 11);
    t = t ^ (t & rot(t, 5));
    b_head = t;
  endfunction
  function automatic logic [W-1:0] b_tail (input logic [W-1:0] x);   // 3 levels
    logic [W-1:0] t;
    t = x ^ rot(x, 13);
    t = t & ZERO_MASK;                 // <-- NOT SURJECTIVE
    b_tail = t ^ rot(t, 2);
  endfunction

  // ---- C: 2 levels ----------------------------------------------------------
  function automatic logic [W-1:0] stage_c (input logic [W-1:0] x);
    stage_c = (x ^ rot(x, 17)) ^ (x & rot(x, 23));
  endfunction

  logic [W-1:0] in_q, mid_q, out_q;

  always_ff @(posedge clk) begin
    if (!rst_n) in_q <= '0;
    else        in_q <= din;
  end

  // 8 levels of logic land on mid_q; only 2 leave it.
  always_ff @(posedge clk) begin
    if (!rst_n) mid_q <= MID_RESET;
    else        mid_q <= b_tail(b_head(stage_a(in_q)));
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= '0;
    else        out_q <= stage_c(mid_q);
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r32_backward_reset_preimage_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r32_backward_reset_preimage (
    input  logic clk,
    input  logic rst_n,
    input  logic [7:0] din,
    output logic [7:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [7:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [255:0] dout_c;
  logic [255:0] din_sr, din_word;
  logic [4:0] din_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_sr <= '0; din_word <= '0; din_cnt <= '0;
    end else begin
      din_sr  <= {din_sr[247:0], din_iq};
      din_cnt <= (din_cnt == 31) ? '0 : din_cnt + 1'b1;
      // word complete on the last beat: latch it, hold it stable
      if (din_cnt == 31)
        din_word <= {din_sr[247:0], din_iq};
    end
  end
  logic [255:0] dout_sr;
  logic [4:0] dout_cnt;
  always_ff @(posedge clk) begin
    if (!rst_n) begin dout_sr <= '0; dout_cnt <= '0; end
    else begin
      dout_cnt <= (dout_cnt == 31) ? '0 : dout_cnt + 1'b1;
      dout_sr  <= (dout_cnt == 0) ? dout_c : {dout_sr[247:0], 8'h0};
    end
  end

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r32_backward_reset_preimage_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_word),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_sr[255:248];
    end
  end

endmodule
