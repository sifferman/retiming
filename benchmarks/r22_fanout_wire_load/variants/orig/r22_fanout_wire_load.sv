// r22 -- fanout_wire_load  (ORIGINAL)
//
//   (ctl_q : 6 bits) ------------------> 256 lanes --> (lane_q)
//
// The scaled-up form of r05.  One 6-bit control register drives 256 datapath
// lanes; at the declared 0.35 density the die is deliberately loose, so after
// placement the control net spans a large fraction of it and its load is wire
// capacitance rather than pin capacitance.
//
// r05 tested the same idea at 48 lanes and 479 cells, and manual cloning LOST
// there: +39% wirelength and +52% power for 66 ps of timing.  Cloning a driver can
// only pay off once its loads are far enough apart that replacing one long net
// with several short ones is a net win.  This benchmark is sized to find out
// whether that crossover exists at a scale we can place and route.

module r22_fanout_wire_load_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [3:0]  cmd,
    input  logic [15:0] din,
    output logic [3:0]  dout
);

  localparam int LANES = 256;

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  // Per-lane work: deep enough that 256 lanes make a physically large die, which
  // is the whole point -- the control net has to actually be long.
  function automatic logic [3:0] lane_fn (input logic [5:0]  ctl,
                                          input logic [15:0] d,
                                          input int          idx);
    logic [15:0] v;
    v = rnd(rnd(d ^ 16'(idx * 16'h9E37), 16'h7B15, 16'h5A5A), 16'hC2B2, 16'h0F1E);
    lane_fn = { ctl[0] ? v[3] : v[11],
                ctl[1] ? v[2] : v[10],
                ctl[2] ^ (^v[7:0]),
                ctl[3] ? v[0] : (|v[15:8]) };
  endfunction

  logic [5:0] ctl_q;
  always_ff @(posedge clk) begin
    if (!rst_n) ctl_q <= 6'b000001;
    else        ctl_q <= {ctl_q[4:0], ctl_q[5] ^ cmd[0]} ^ {2'b0, cmd};
  end

  logic [15:0] din_q;
  always_ff @(posedge clk) begin
    if (!rst_n) din_q <= 16'h0;
    else        din_q <= din;
  end

  logic [4*LANES-1:0] lane_q;

  always_ff @(posedge clk) begin
    if (!rst_n) lane_q <= '0;
    else begin
      for (int i = 0; i < LANES; i++)
        lane_q[i*4 +: 4] <= lane_fn(ctl_q, din_q, i);
    end
  end

  // Reduce the 256 lanes to a narrow output so the port count stays sane; the xor
  // tree is shallow relative to the lane logic and is not the point of interest.
  logic [3:0] red;
  always_comb begin
    red = 4'h0;
    for (int i = 0; i < LANES; i++) red = red ^ lane_q[i*4 +: 4];
  end

  logic [3:0] out_q;
  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 4'h0;
    else        out_q <= red;
  end

  assign dout = out_q;

endmodule

