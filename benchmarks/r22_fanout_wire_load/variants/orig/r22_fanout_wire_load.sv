// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r22_fanout_wire_load (
    input  logic clk,
    input  logic rst_n,
    input  logic [3:0] cmd,
    input  logic [15:0] din,
    output logic [3:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [3:0] cmd_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [3:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      cmd_iq <= '0;
      din_iq <= '0;
    end else begin
      cmd_iq <= cmd;
      din_iq <= din;
    end
  end

  r22_fanout_wire_load_core u_core (
    .clk(clk), .rst_n(rst_n),
    .cmd(cmd_iq),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
