// r22 -- fanout_wire_load  (HAND-CLONED REFERENCE)
//
//   (ctl_q) --> next-state / control use only
//   (rep_q[0..15]) --> lanes, 16 lanes per clone
//
// Sixteen clones of the control register, each driving 16 lanes.  Identical D,
// identical reset value, so the transform is trivially behaviour-preserving and
// strictly latency-preserving.
//
// As in r05, the clones only survive because flop merging is disabled for this
// benchmark in common.tcl -- symmetrically, for every variant, so the two runs
// differ only in RTL.

module r22_fanout_wire_load_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [3:0]  cmd,
    input  logic [15:0] din,
    output logic [3:0]  dout
);

  localparam int LANES = 256;

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  // Per-lane work: deep enough that 256 lanes make a physically large die, which
  // is the whole point -- the control net has to actually be long.
  function automatic logic [3:0] lane_fn (input logic [5:0]  ctl,
                                          input logic [15:0] d,
                                          input int          idx);
    logic [15:0] v;
    v = rnd(rnd(d ^ 16'(idx * 16'h9E37), 16'h7B15, 16'h5A5A), 16'hC2B2, 16'h0F1E);
    lane_fn = { ctl[0] ? v[3] : v[11],
                ctl[1] ? v[2] : v[10],
                ctl[2] ^ (^v[7:0]),
                ctl[3] ? v[0] : (|v[15:8]) };
  endfunction

  localparam int REPS = 16;

  logic [5:0] ctl_d;
  logic [5:0] ctl_q;
  always_comb ctl_d = {ctl_q[4:0], ctl_q[5] ^ cmd[0]} ^ {2'b0, cmd};

  // Original register: now used only for the control feedback loop.
  always_ff @(posedge clk) begin
    if (!rst_n) ctl_q <= 6'b000001;
    else        ctl_q <= ctl_d;
  end

  // Clones: same D, same reset value, one per group of 16 lanes.
  (* dont_touch = "yes" *) (* preserve = "true" *) (* syn_preserve = "1" *)
  logic [5:0] rep_q [REPS];

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      for (int r = 0; r < REPS; r++) rep_q[r] <= 6'b000001;
    end else begin
      for (int r = 0; r < REPS; r++) rep_q[r] <= ctl_d;
    end
  end

  logic [15:0] din_q;
  always_ff @(posedge clk) begin
    if (!rst_n) din_q <= 16'h0;
    else        din_q <= din;
  end

  logic [4*LANES-1:0] lane_q;

  always_ff @(posedge clk) begin
    if (!rst_n) lane_q <= '0;
    else begin
      for (int i = 0; i < LANES; i++)
        lane_q[i*4 +: 4] <= lane_fn(rep_q[(i * REPS) / LANES], din_q, i);
    end
  end

  // Reduce the 256 lanes to a narrow output so the port count stays sane; the xor
  // tree is shallow relative to the lane logic and is not the point of interest.
  logic [3:0] red;
  always_comb begin
    red = 4'h0;
    for (int i = 0; i < LANES; i++) red = red ^ lane_q[i*4 +: 4];
  end

  logic [3:0] out_q;
  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 4'h0;
    else        out_q <= red;
  end

  assign dout = out_q;

endmodule

