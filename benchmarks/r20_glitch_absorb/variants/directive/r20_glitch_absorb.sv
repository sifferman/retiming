// r20 -- glitch_absorb  (DIRECTIVE VARIANT)
//
//   din --> (s1_q) --[ deep XOR network ]--[ 32 lanes of logic ]--> (out_q)
//
// The XOR network and the 32-lane cone share one pipeline stage.  An XOR tree is
// the worst case for glitching: unbalanced arrival times mean each output toggles
// several times before settling, and here every one of those transitions
// propagates into all 32 downstream lanes.
//
// Moving the register to sit immediately after the XOR network absorbs the
// glitches at the flop boundary, so the lanes see only the settled value and
// switch once per cycle.  Same latency, near-identical period, much less switched
// capacitance.
//
// This is glitch power, which is invisible to a delay-driven retimer -- and also
// invisible to a probabilistic power estimate.  It has to be measured with real
// activity data, which is why this benchmark is scored from a VCD/SAIF run.

module r20_glitch_absorb_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [31:0] dout
);

  // Deliberately unbalanced XOR network: each output bit reduces a different,
  // awkward subset, so arrival times differ and glitches are plentiful.
  function automatic logic [15:0] xor_net (input logic [15:0] x);
    logic [15:0] y;
    for (int i = 0; i < 16; i++) begin
      logic acc;
      acc = 1'b0;
      for (int j = 0; j <= i; j++) acc = acc ^ x[(i + j * 3) % 16];
      y[i] = acc;
    end
    xor_net = y;
  endfunction

  function automatic logic lane_fn (input logic [15:0] v, input int idx);
    logic [15:0] r;
    r = {v[7:0], v[15:8]} ^ 16'(idx * 16'h9E37);
    lane_fn = (^(r & 16'(idx + 1))) ^ (|r[7:0]) ^ r[idx % 16];
  endfunction

  logic [15:0] s1_q;
  logic [31:0] out_q;

  always_ff @(posedge clk) begin
    if (!rst_n) s1_q <= 16'h0;
    else        s1_q <= din;
  end

  // XOR network AND all 32 lanes in one stage: glitches fan out.
  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 32'h0;
    else begin
      for (int i = 0; i < 32; i++) out_q[i] <= lane_fn(xor_net(s1_q), i);
    end
  end

  assign dout = out_q;

endmodule

