// r20 -- glitch_absorb  (HAND-RETIMED REFERENCE)
//
//   din --[ deep XOR network ]--> (xr_q) --[ 32 lanes of logic ]--> (out_q)
//
// The register moved forward across the XOR network.  Two register stages before,
// two after; identical I/O latency.
//
// The XOR network's glitches now terminate at xr_q instead of propagating into 32
// lanes, so the lanes see one clean transition per cycle.
//
// Reset: the original's second stage latches lane_fn(xor_net(s1_q)) with s1_q
// still zero on the first post-reset cycle, so xr_q must reset to xor_net(0) --
// derived here rather than assumed.

module r20_glitch_absorb_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [31:0] dout
);

  function automatic logic [15:0] xor_net (input logic [15:0] x);
    logic [15:0] y;
    for (int i = 0; i < 16; i++) begin
      logic acc;
      acc = 1'b0;
      for (int j = 0; j <= i; j++) acc = acc ^ x[(i + j * 3) % 16];
      y[i] = acc;
    end
    xor_net = y;
  endfunction

  function automatic logic lane_fn (input logic [15:0] v, input int idx);
    logic [15:0] r;
    r = {v[7:0], v[15:8]} ^ 16'(idx * 16'h9E37);
    lane_fn = (^(r & 16'(idx + 1))) ^ (|r[7:0]) ^ r[idx % 16];
  endfunction

  localparam logic [15:0] XR_RESET = xor_net(16'h0);

  logic [15:0] xr_q;
  logic [31:0] out_q;

  // Stage 1 absorbed the XOR network.
  always_ff @(posedge clk) begin
    if (!rst_n) xr_q <= XR_RESET;
    else        xr_q <= xor_net(din);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 32'h0;
    else begin
      for (int i = 0; i < 32; i++) out_q[i] <= lane_fn(xr_q, i);
    end
  end

  assign dout = out_q;

endmodule

