// r15 -- hier_boundary_block  (HAND-RETIMED REFERENCE)
//
//   PI --[ u_a : 3 rounds -> (p) -> 3 rounds ]--> mid --[ u_b : (r2) ]--> PO
//
// B's input register moved backward across the module boundary and three rounds
// into A.  A is now sequential (it gained clk/rst_n ports); B lost a register.
// Two registers total before and after, identical I/O latency.
//
// Reset
// -----
// The original drives dout = 0 for the first cycles after reset, and B's
// remaining register computes r2 <= mid ^ rot(mid).  For that to be zero we need
// mid = 0 on the corresponding cycle, so A's new register must reset to the value
// its remaining three rounds map to zero: p_reset = a2^-1(0).  Derived at
// elaboration time from the inverse rounds.
//
// Note that the port list of u_a changed.  That is the real cost of this
// transform and the reason tools avoid it: retiming across a hierarchy boundary
// rewrites module interfaces, which conflicts with hierarchical closure, reuse,
// and any preserved-boundary constraint.

module r15_sub_a (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] a2_inv (input logic [15:0] y);
    a2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] P_RESET = a2_inv(16'h0);

  logic [15:0] p;

  always_ff @(posedge clk) begin
    if (!rst_n) p <= P_RESET;
    else        p <= a1(din);
  end

  always_comb dout = a2(p);
endmodule
module r15_sub_b (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  logic [15:0] r2;

  // The input register is gone -- it now lives in u_a.
  always_ff @(posedge clk) begin
    if (!rst_n) r2 <= 16'h0;
    else        r2 <= din ^ {din[7:0], din[15:8]};
  end

  assign dout = r2;
endmodule
module r15_hier_boundary_block_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  logic [15:0] mid;

  r15_sub_a u_a (.clk(clk), .rst_n(rst_n), .din(din), .dout(mid));
  r15_sub_b u_b (.clk(clk), .rst_n(rst_n), .din(mid),  .dout(dout));
endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r15_hier_boundary_block_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r15_hier_boundary_block (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r15_hier_boundary_block_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
