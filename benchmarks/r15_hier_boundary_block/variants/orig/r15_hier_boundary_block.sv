// r15 -- hier_boundary_block  (ORIGINAL)
//
//   PI --[ u_a : 6 rounds, PURELY COMBINATIONAL ]--> mid --[ u_b : (r1) -> (r2) ]--> PO
//
// Submodule A is deep and has no registers at all.  Submodule B registers its
// input immediately, then does almost nothing.
//
// The critical path therefore starts at a primary input, traverses the whole of
// A, crosses the module boundary, and ends at a register inside B.  There is no
// register in A to push forward, so the only fix is to move B's input register
// BACKWARD across the module boundary and into the middle of A.
//
// That is a legal retiming, but it relocates a register from one module to
// another -- which is exactly what a tool preserving hierarchy will not do.

module r15_sub_a (
    input  logic [15:0] din,
    output logic [15:0] dout
);
  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  // All six rounds, no registers.
  always_comb dout = rnd(rnd(rnd(rnd(rnd(rnd(din, K1, C1), K2, C2), K3, C3),
                                  K4, C4), K5, C5), K6, C6);
endmodule
module r15_sub_b (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  logic [15:0] r1, r2;

  // Registers the boundary signal immediately -- and this is the endpoint of the
  // long path that starts back at the top-level primary inputs.
  always_ff @(posedge clk) begin
    if (!rst_n) r1 <= 16'h0;
    else        r1 <= din;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) r2 <= 16'h0;
    else        r2 <= r1 ^ {r1[7:0], r1[15:8]};
  end

  assign dout = r2;
endmodule
module r15_hier_boundary_block_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  logic [15:0] mid;

  r15_sub_a u_a (.din(din),  .dout(mid));
  r15_sub_b u_b (.clk(clk), .rst_n(rst_n), .din(mid), .dout(dout));
endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r15_hier_boundary_block_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r15_hier_boundary_block (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r15_hier_boundary_block_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
