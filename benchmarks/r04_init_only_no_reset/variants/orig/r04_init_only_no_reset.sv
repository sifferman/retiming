// r04 -- init_only_no_reset  (ORIGINAL)
//
// The r01 shape with the reset removed entirely: registers have a power-up value
// and nothing else.
//
// The two targets treat this completely differently, which is the point:
//   * Artix-7 -- the value is real.  Every FDRE has an INIT attribute honoured at
//     configuration, so a retimed register needs its INIT recomputed exactly the
//     way r01 needed a new reset constant.
//   * gf180mcu -- there is no initial-value concept in an ASIC standard cell at
//     all.  The value is unimplementable and simply ignored, so the retimer has
//     NO initial-state constraint to satisfy and should be at its freest here.
//
// So r04 should be the easiest Class A case on ASIC and a genuine constraint on
// FPGA.  Any tool that finds r01 hard and r04 equally hard is not reasoning about
// initial state at all.

module r04_init_only_no_reset_core (
    input  logic        clk,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  localparam logic [15:0] Q_INIT = 16'hBEEF;

  logic [15:0] q     = Q_INIT;
  logic [15:0] out_q = 16'h0000;

  always_ff @(posedge clk) q     <= a2(a1(din));
  always_ff @(posedge clk) out_q <= q ^ {q[7:0], q[15:8]};

  assign dout = out_q;

endmodule

