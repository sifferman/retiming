// r04 -- init_only_no_reset  (HAND-RETIMED REFERENCE)
//
// The same backward move as r01: `q` retimed across a2.  The new register's
// power-up value is the a2 pre-image of the original's, derived at elaboration
// time rather than hard-coded.
//
// On gf180mcu this initial value has no hardware meaning and is ignored, so the
// reference is functionally identical to a version with no init at all.  On
// Artix-7 it becomes the FDRE INIT attribute and is load-bearing.

module r04_init_only_no_reset_core (
    input  logic        clk,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] a2_inv (input logic [15:0] y);
    a2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] Q_INIT  = 16'hBEEF;
  localparam logic [15:0] Q1_INIT = a2_inv(Q_INIT);

  logic [15:0] q1    = Q1_INIT;
  logic [15:0] out_q = 16'h0000;
  logic [15:0] a2q;

  always_ff @(posedge clk) q1 <= a1(din);
  always_comb a2q = a2(q1);
  always_ff @(posedge clk) out_q <= a2q ^ {a2q[7:0], a2q[15:8]};

  assign dout = out_q;

endmodule

