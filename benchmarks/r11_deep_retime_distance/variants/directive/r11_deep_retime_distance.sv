// r11 -- deep_retime_distance  (DIRECTIVE VARIANT)
// Original RTL; the retiming is requested from the tool.
//
//   PI --[ 24 invertible rounds ]--> (r1) -> (r2) -> (r3) --> PO
//
// All 24 rounds of logic sit in front of the first register; the other two
// registers are a shift register doing nothing.  Latency from din to dout is
// three cycles.
//
// Balancing this needs registers moved 6, 12 and 18 rounds upstream.  Every move
// is legal, so this benchmark measures how far a retimer is *willing* to move a
// register, not whether it may.
//
// The rounds are bijections (rotate, xor constant, add constant).  That is what
// makes the reference solution's reset values exactly computable -- see the
// retimed variant.

module r11_deep_retime_distance_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [31:0] din,
    output logic [31:0] dout
);

  function automatic logic [31:0] kk (input int i); kk = 32'h9E37_79B9 * (i + 1); endfunction
  function automatic logic [31:0] cc (input int i); cc = 32'h7F4A_7C15 * (i + 1); endfunction

  function automatic logic [31:0] rnd (input logic [31:0] x, input int i);
    logic [31:0] t;
    t   = {x[30:0], x[31]} ^ kk(i);
    rnd = t + cc(i);
  endfunction

  // Six rounds per quarter, written out explicitly rather than as a loop so that
  // every tool in the suite elaborates it identically.
  function automatic logic [31:0] q1f (input logic [31:0] x);
    q1f = rnd(rnd(rnd(rnd(rnd(rnd(x, 0), 1), 2), 3), 4), 5);
  endfunction
  function automatic logic [31:0] q2f (input logic [31:0] x);
    q2f = rnd(rnd(rnd(rnd(rnd(rnd(x, 6), 7), 8), 9), 10), 11);
  endfunction
  function automatic logic [31:0] q3f (input logic [31:0] x);
    q3f = rnd(rnd(rnd(rnd(rnd(rnd(x, 12), 13), 14), 15), 16), 17);
  endfunction
  function automatic logic [31:0] q4f (input logic [31:0] x);
    q4f = rnd(rnd(rnd(rnd(rnd(rnd(x, 18), 19), 20), 21), 22), 23);
  endfunction

  logic [31:0] r1, r2, r3;

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      r1 <= 32'h0;
      r2 <= 32'h0;
      r3 <= 32'h0;
    end else begin
      r1 <= q4f(q3f(q2f(q1f(din))));   // all 24 rounds, one stage
      r2 <= r1;
      r3 <= r2;
    end
  end

  assign dout = r3;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r11_deep_retime_distance_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r11_deep_retime_distance (
    input  logic clk,
    input  logic rst_n,
    input  logic [31:0] din,
    output logic [31:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [31:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [31:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r11_deep_retime_distance_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
