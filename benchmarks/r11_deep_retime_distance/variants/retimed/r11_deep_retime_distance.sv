// r11 -- deep_retime_distance  (HAND-RETIMED REFERENCE)
//
//   PI --[6]--> (q1) --[6]--> (q2) --[6]--> (q3) --[6]--> PO
//
// Same three registers, same three-cycle latency, but each now has six rounds in
// front of it instead of 24/0/0.  The retiming distances are 18, 12 and 6 rounds.
//
// Reset values
// ------------
// The original resets all three registers to zero, so `dout` must read zero for
// the first three cycles after reset.  After the move, `dout` is a function of
// q3, so zero at the output implies a specific non-zero value in each register:
//
//     q3_reset = q4f^-1(0)
//     q2_reset = (q4f o q3f)^-1(0)
//     q1_reset = (q4f o q3f o q2f)^-1(0)
//
// Each round is a bijection, so those pre-images exist and are unique.  They are
// computed here at elaboration time from the inverse rounds rather than being
// hard-coded, so the reference cannot silently drift out of agreement with the
// original.  This is exactly the reset bookkeeping that makes long backward
// retiming moves unattractive to a production tool.

module r11_deep_retime_distance_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [31:0] din,
    output logic [31:0] dout
);

  function automatic logic [31:0] kk (input int i); kk = 32'h9E37_79B9 * (i + 1); endfunction
  function automatic logic [31:0] cc (input int i); cc = 32'h7F4A_7C15 * (i + 1); endfunction

  function automatic logic [31:0] rnd (input logic [31:0] x, input int i);
    logic [31:0] t;
    t   = {x[30:0], x[31]} ^ kk(i);
    rnd = t + cc(i);
  endfunction

  // Exact inverse: undo the add, undo the xor, rotate right.
  function automatic logic [31:0] rnd_inv (input logic [31:0] y, input int i);
    logic [31:0] t;
    t       = (y - cc(i)) ^ kk(i);
    rnd_inv = {t[0], t[31:1]};
  endfunction

  function automatic logic [31:0] q1f (input logic [31:0] x);
    q1f = rnd(rnd(rnd(rnd(rnd(rnd(x, 0), 1), 2), 3), 4), 5);
  endfunction
  function automatic logic [31:0] q2f (input logic [31:0] x);
    q2f = rnd(rnd(rnd(rnd(rnd(rnd(x, 6), 7), 8), 9), 10), 11);
  endfunction
  function automatic logic [31:0] q3f (input logic [31:0] x);
    q3f = rnd(rnd(rnd(rnd(rnd(rnd(x, 12), 13), 14), 15), 16), 17);
  endfunction
  function automatic logic [31:0] q4f (input logic [31:0] x);
    q4f = rnd(rnd(rnd(rnd(rnd(rnd(x, 18), 19), 20), 21), 22), 23);
  endfunction

  function automatic logic [31:0] q2b (input logic [31:0] y);
    q2b = rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(y, 11), 10), 9), 8), 7), 6);
  endfunction
  function automatic logic [31:0] q3b (input logic [31:0] y);
    q3b = rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(y, 17), 16), 15), 14), 13), 12);
  endfunction
  function automatic logic [31:0] q4b (input logic [31:0] y);
    q4b = rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(rnd_inv(y, 23), 22), 21), 20), 19), 18);
  endfunction

  localparam logic [31:0] Q3_RESET = q4b(32'h0);
  localparam logic [31:0] Q2_RESET = q3b(q4b(32'h0));
  localparam logic [31:0] Q1_RESET = q2b(q3b(q4b(32'h0)));

  logic [31:0] q1, q2, q3;

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      q1 <= Q1_RESET;
      q2 <= Q2_RESET;
      q3 <= Q3_RESET;
    end else begin
      q1 <= q1f(din);
      q2 <= q2f(q1);
      q3 <= q3f(q2);
    end
  end

  assign dout = q4f(q3);

endmodule

