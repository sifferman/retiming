  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
