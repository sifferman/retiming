// r01 -- reset_backward_barrier  (DIRECTIVE VARIANT)
//
// Identical RTL to variants/orig, plus vendor attributes asking the tool to do
// the retiming itself.  Paired with directives.tcl for the Cadence side.
// Vivado reads RETIMING_BACKWARD; Genus ignores it harmlessly.
//
// Shape:   PI --[ A1 : 3 invertible rounds ]--[ A2 : 3 invertible rounds ]--> q --[ B ]--> out
//                            ^^^^^^^^ the whole 6-round chain is combinational ^^^^^^^^
//
// The critical path is  primary input -> A1 -> A2 -> q.  It is long.
// The path  q -> B -> out_q  is short.  The register cut is badly unbalanced.
//
// There is NO register upstream of A1 to push forward: the chain is fed directly by
// primary inputs. So the *only* legal way to balance this is to retime `q` BACKWARD
// into the middle of the chain -- and `q` has a synchronous reset, which means the
// retimed register needs a new reset value equal to the A2 pre-image of Q_RESET.
//
// Genus and Vivado both decline this. See README.md.

module r01_reset_backward_barrier_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  // ---------------------------------------------------------------
  // Invertible round: rotate-left-1, xor constant, add constant.
  // Each round is a bijection on 16 bits, so any pre-image we need
  // later is guaranteed to exist and to be unique.
  // ---------------------------------------------------------------
  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  // A1 = rounds 1..3
  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction

  // A2 = rounds 4..6
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  localparam logic [15:0] Q_RESET = 16'hBEEF;

  logic [15:0] chain;
  (* RETIMING_BACKWARD = "3" *) logic [15:0] q;
  logic [15:0] out_q;

  // One deep combinational cloud, no registers inside.
  always_comb chain = a2(a1(din));

  // The reset flop that has to move backward.
  always_ff @(posedge clk) begin
    if (!rst_n) q <= Q_RESET;
    else        q <= chain;
  end

  // Short logic after the flop -- this is where the slack is.
  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0000;
    else        out_q <= q ^ {q[7:0], q[15:8]};
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r01_reset_backward_barrier_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r01_reset_backward_barrier (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      din_iq <= '0;
    end else begin
      din_iq <= din;
    end
  end

  r01_reset_backward_barrier_core u_core (
    .clk(clk), .rst_n(rst_n),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
