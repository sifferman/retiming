// r03 -- async_reset_blocker  (HAND-RETIMED REFERENCE)
//
// The same backward move as r01's reference: `q` retimed back across a2, with the
// new reset value derived as a2^-1(Q_RESET) at elaboration time.  Crucially the
// reset stays ASYNCHRONOUS, so this is a like-for-like replacement and the only
// variable is the reset flavour.

module r03_async_reset_blocker_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  // Exact inverse of rnd: undo the add, undo the xor, rotate right.
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction

  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  function automatic logic [15:0] a2_inv (input logic [15:0] y);
    a2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] Q_RESET  = 16'hBEEF;
  // The retimed reset value, derived rather than guessed.
  localparam logic [15:0] Q1_RESET = a2_inv(Q_RESET);

  logic [15:0] q1;
  logic [15:0] out_q;

  // Stage 1 now ends halfway through the chain.
  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) q1 <= Q1_RESET;
    else        q1 <= a1(din);
  end

  // Stage 2 absorbed A2 plus the original short logic B.
  logic [15:0] a2q;
  always_comb a2q = a2(q1);

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) out_q <= 16'h0000;
    else        out_q <= a2q ^ {a2q[7:0], a2q[15:8]};
  end

  assign dout = out_q;

`ifdef RETIMING_ASSERT_PREIMAGE
  // Elaboration-time proof that the derived reset value is correct.
  initial begin
    if (a2(Q1_RESET) !== Q_RESET) begin
      $fatal(1, "r01: a2(Q1_RESET)=%h != Q_RESET=%h", a2(Q1_RESET), Q_RESET);
    end
  end
`endif

endmodule

