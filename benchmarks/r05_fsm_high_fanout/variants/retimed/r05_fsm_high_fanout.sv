// r05 -- fsm_high_fanout  (HAND-RETIMED / DUPLICATED REFERENCE)
//
//            (state_q) --> next_state (loop)          <- untouched, still in the loop
//            (rep_q[0]) --> lanes  0.. 5
//            (rep_q[1]) --> lanes  6..11
//              ...
//            (rep_q[7]) --> lanes 42..47
//
// Eight clones of the state register, each driving six lanes, plus the original
// kept exclusively for the next-state loop.  Every clone has the same D input and
// the same reset value as the original, so the transform is trivially
// behaviour-preserving and strictly latency-preserving.
//
// Why the dont_touch matters
// --------------------------
// Nine registers with identical D and identical reset are, to a synthesis tool,
// nine copies of the same thing -- and sequential merging will collapse them
// straight back into one, silently undoing the whole benchmark.  The clones are
// therefore marked dont_touch/preserve.  This is not a trick to win the
// comparison: it is the honest admission that the tools' own optimiser actively
// fights this transform, and a real retiming tool would need to make the
// placement-aware cloning decision *and* defend it from its own sweep passes.

module r05_fsm_high_fanout_core (
    input  logic                  clk,
    input  logic                  rst_n,
    input  logic [3:0]            cmd,
    input  logic [15:0]           din,
    output logic [47:0]           dout
);

  localparam int LANES = 48;
  localparam int REPS  = 8;

  localparam logic [5:0] S_IDLE = 6'b000001;
  localparam logic [5:0] S_LOAD = 6'b000010;
  localparam logic [5:0] S_EXEC = 6'b000100;
  localparam logic [5:0] S_HOLD = 6'b001000;
  localparam logic [5:0] S_DRAIN= 6'b010000;
  localparam logic [5:0] S_DONE = 6'b100000;

  logic [5:0] state_q, state_d;
  logic [15:0] din_q;

  always_comb begin
    state_d = state_q;
    unique case (1'b1)
      state_q[0]: state_d = cmd[0] ? S_LOAD  : S_IDLE;
      state_q[1]: state_d = cmd[1] ? S_EXEC  : S_LOAD;
      state_q[2]: state_d = cmd[2] ? S_HOLD  : S_EXEC;
      state_q[3]: state_d = cmd[3] ? S_DRAIN : S_HOLD;
      state_q[4]: state_d = cmd[0] ? S_DONE  : S_DRAIN;
      state_q[5]: state_d = S_IDLE;
      default:    state_d = S_IDLE;
    endcase
  end

  // The original register: now feeds ONLY the next-state logic, so its fanout is
  // 6 loads instead of ~290.
  always_ff @(posedge clk) begin
    if (!rst_n) state_q <= S_IDLE;
    else        state_q <= state_d;
  end

  // Clones.  Same D, same reset, one per lane group.
  (* dont_touch = "yes" *) (* preserve = "true" *) (* syn_preserve = "1" *)
  logic [5:0] rep_q [REPS];

  always_ff @(posedge clk) begin
    if (!rst_n) begin
      for (int r = 0; r < REPS; r++) rep_q[r] <= S_IDLE;
    end else begin
      for (int r = 0; r < REPS; r++) rep_q[r] <= state_d;
    end
  end

  always_ff @(posedge clk) begin
    if (!rst_n) din_q <= 16'h0;
    else        din_q <= din;
  end

  function automatic logic lane_fn (input logic [5:0] st,
                                    input logic [15:0] d,
                                    input int          idx);
    logic [15:0] rot;
    logic        acc;
    rot = {d[7:0], d[15:8]} ^ 16'(idx * 16'h9E37);
    acc = ^(rot & 16'(idx + 1));
    lane_fn = (st[0] &  acc)
            | (st[1] & ~acc)
            | (st[2] &  (^rot))
            | (st[3] &  rot[idx % 16])
            | (st[4] & ~rot[(idx + 3) % 16])
            | (st[5] &  (|rot[7:0]));
  endfunction

  logic [LANES-1:0] lane_q;

  always_ff @(posedge clk) begin
    if (!rst_n) lane_q <= '0;
    else begin
      // Lane i reads the clone that owns its group.
      for (int i = 0; i < LANES; i++)
        lane_q[i] <= lane_fn(rep_q[(i * REPS) / LANES], din_q, i);
    end
  end

  assign dout = lane_q;

endmodule

