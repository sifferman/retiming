// r05 -- fsm_high_fanout  (ORIGINAL)
//
//                +---------------- next_state (short, in a LOOP) ------+
//                |                                                    |
//                v                                                    |
//            (state_q) ------------------------------------------------+
//                |
//                +--> lane 0  --[ logic ]--> (lane_q[0])
//                +--> lane 1  --[ logic ]--> (lane_q[1])
//                ...
//                +--> lane 47 --[ logic ]--> (lane_q[47])
//
// One 6-bit one-hot state register drives 48 datapath lanes AND its own
// next-state logic.  The state net has ~48x6 loads and, once placed, physically
// spans the die.
//
// Why this is not a classical retiming problem
// --------------------------------------------
// state_q sits in a feedback loop, so retiming cannot move it: any retiming that
// shifts a register out of a loop changes the loop's register count and therefore
// the circuit's behaviour.  The transform that actually helps is *duplication* --
// clone state_q, leave one copy driving the next-state logic, and scatter the
// other copies among the lanes so each drives a short, local net.
//
// Duplication is not expressible in the Leiserson-Saxe retiming formulation at
// all, which is the point of this benchmark.  Production tools do clone for
// fanout as a separate optimisation; the measurement here is whether that
// achieves what a deliberate, placement-aware manual cloning achieves.

module r05_fsm_high_fanout_core (
    input  logic                  clk,
    input  logic                  rst_n,
    input  logic [3:0]            cmd,
    input  logic [15:0]           din,
    output logic [47:0]           dout
);

  // One-hot, 6 states.  One-hot deliberately: it makes the fanout wide (6 bits
  // to every lane) rather than narrow.
  localparam int LANES = 48;
  localparam int REPS  = 8;

  localparam logic [5:0] S_IDLE = 6'b000001;
  localparam logic [5:0] S_LOAD = 6'b000010;
  localparam logic [5:0] S_EXEC = 6'b000100;
  localparam logic [5:0] S_HOLD = 6'b001000;
  localparam logic [5:0] S_DRAIN= 6'b010000;
  localparam logic [5:0] S_DONE = 6'b100000;

  logic [5:0] state_q, state_d;
  logic [15:0] din_q;

  // Next-state logic: short.  The loop bound is nowhere near critical.
  always_comb begin
    state_d = state_q;
    unique case (1'b1)
      state_q[0]: state_d = cmd[0] ? S_LOAD  : S_IDLE;
      state_q[1]: state_d = cmd[1] ? S_EXEC  : S_LOAD;
      state_q[2]: state_d = cmd[2] ? S_HOLD  : S_EXEC;
      state_q[3]: state_d = cmd[3] ? S_DRAIN : S_HOLD;
      state_q[4]: state_d = cmd[0] ? S_DONE  : S_DRAIN;
      state_q[5]: state_d = S_IDLE;
      default:    state_d = S_IDLE;
    endcase
  end

  always_ff @(posedge clk) begin
    if (!rst_n) state_q <= S_IDLE;
    else        state_q <= state_d;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) din_q <= 16'h0;
    else        din_q <= din;
  end

  // Per-lane logic.  Each lane reads the whole one-hot state vector plus its own
  // slice of data -- moderate depth, but 48 copies of it, all fed from one net.
  function automatic logic lane_fn (input logic [5:0] st,
                                    input logic [15:0] d,
                                    input int          idx);
    logic [15:0] rot;
    logic        acc;
    rot = {d[7:0], d[15:8]} ^ 16'(idx * 16'h9E37);
    acc = ^(rot & 16'(idx + 1));
    lane_fn = (st[0] &  acc)
            | (st[1] & ~acc)
            | (st[2] &  (^rot))
            | (st[3] &  rot[idx % 16])
            | (st[4] & ~rot[(idx + 3) % 16])
            | (st[5] &  (|rot[7:0]));
  endfunction

  logic [LANES-1:0] lane_q;

  always_ff @(posedge clk) begin
    if (!rst_n) lane_q <= '0;
    else begin
      for (int i = 0; i < LANES; i++) lane_q[i] <= lane_fn(state_q, din_q, i);
    end
  end

  assign dout = lane_q;

endmodule

