// r13 -- retime_around_sram  (ORIGINAL)
//
//   addr --[ A1: 3 rounds ]--[ A2: 3 rounds ]--> (a_q) --> MEM addr
//                                                          MEM --> (rd_q) --[ xor ]--> (out_q)
//
// The critical path is the address computation: six rounds from a primary input to
// the register that drives the memory's address port.  The read path itself
// (a_q -> memory -> rd_q) is comparatively short.
//
// Rebalancing means moving a_q backward through A2 -- which is legal, but the
// register in question is the one feeding a memory address pin:
//   * ASIC: the memory is a macro with a fixed timing model.  Tools do not
//     restructure logic at macro pins, so a register bound to one tends to be
//     treated as immovable.
//   * Artix-7: a register driving a BRAM address is normally absorbed INTO the
//     BRAM primitive.  Moving it upstream gives up that absorption, so the
//     transform has a real cost the tool has to weigh rather than just a benefit.
//
// The memory has a write port driven from the top-level inputs and no reset, so
// both variants see identical contents on identical cycles.

module r13_retime_around_sram_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] addr,
    input  logic [15:0] wdata,
    input  logic        we,
    output logic [15:0] dout
);

  localparam int DEPTH_LOG2 = 5;   // 32 entries

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  logic [15:0] mem [1 << DEPTH_LOG2];
  logic [15:0] a_q, rd_q, out_q;

  // Address register: the one that has to move.
  always_ff @(posedge clk) begin
    if (!rst_n) a_q <= 16'h0;
    else        a_q <= a2(a1(addr));
  end

  // Write port, identical in both variants.
  always_ff @(posedge clk) begin
    if (we) mem[addr[DEPTH_LOG2-1:0]] <= wdata;
  end

  // Synchronous read.
  always_ff @(posedge clk) begin
    rd_q <= mem[a_q[DEPTH_LOG2-1:0]];
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0;
    else        out_q <= rd_q ^ 16'hA5A5;
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r13_retime_around_sram_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r13_retime_around_sram (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] addr,
    input  logic [15:0] wdata,
    input  logic we,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] addr_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] wdata_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic we_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      addr_iq <= '0;
      wdata_iq <= '0;
      we_iq <= '0;
    end else begin
      addr_iq <= addr;
      wdata_iq <= wdata;
      we_iq <= we;
    end
  end

  r13_retime_around_sram_core u_core (
    .clk(clk), .rst_n(rst_n),
    .addr(addr_iq),
    .wdata(wdata_iq),
    .we(we_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
