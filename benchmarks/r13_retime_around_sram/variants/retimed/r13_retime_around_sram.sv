// r13 -- retime_around_sram  (HAND-RETIMED REFERENCE)
//
//   addr --[ A1: 3 rounds ]--> (p_q) --[ A2: 3 rounds ]--> MEM addr
//                                                          MEM --> (rd_q) --[ xor ]--> (out_q)
//
// The address register moved backward through A2.  Three rounds now precede the
// register and three follow it, the latter feeding the memory address port
// combinationally.  Same register count, same I/O latency.
//
// Reset
// -----
// The original resets a_q to zero, so the first post-reset read is from address 0.
// After the move, the memory address is a2(p_q), so p_q must reset to the value
// a2 maps to zero: p_reset = a2^-1(0).  a2 is a composition of bijections, so that
// exists and is unique, and it is derived at elaboration time.
//
// Note what this transform costs on an FPGA: the memory address is now driven by
// combinational logic rather than straight off a flop, so the address register can
// no longer be absorbed into the BRAM primitive.  That is a real trade the tool
// would have to evaluate, not a free win.

module r13_retime_around_sram_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] addr,
    input  logic [15:0] wdata,
    input  logic        we,
    output logic [15:0] dout
);

  localparam int DEPTH_LOG2 = 5;

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] a2_inv (input logic [15:0] y);
    a2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] P_RESET = a2_inv(16'h0);

  logic [15:0] mem [1 << DEPTH_LOG2];
  logic [15:0] p_q, rd_q, out_q;
  logic [15:0] mem_addr;

  always_ff @(posedge clk) begin
    if (!rst_n) p_q <= P_RESET;
    else        p_q <= a1(addr);
  end

  // The remaining half of the address computation, now downstream of the register.
  always_comb mem_addr = a2(p_q);

  always_ff @(posedge clk) begin
    if (we) mem[addr[DEPTH_LOG2-1:0]] <= wdata;
  end

  always_ff @(posedge clk) begin
    rd_q <= mem[mem_addr[DEPTH_LOG2-1:0]];
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0;
    else        out_q <= rd_q ^ 16'hA5A5;
  end

  assign dout = out_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r13_retime_around_sram_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r13_retime_around_sram (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] addr,
    input  logic [15:0] wdata,
    input  logic we,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] addr_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] wdata_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic we_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      addr_iq <= '0;
      wdata_iq <= '0;
      we_iq <= '0;
    end else begin
      addr_iq <= addr;
      wdata_iq <= wdata;
      we_iq <= we;
    end
  end

  r13_retime_around_sram_core u_core (
    .clk(clk), .rst_n(rst_n),
    .addr(addr_iq),
    .wdata(wdata_iq),
    .we(we_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
