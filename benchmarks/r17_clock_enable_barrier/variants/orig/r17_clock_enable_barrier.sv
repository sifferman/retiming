// r17 -- clock_enable_barrier  (ORIGINAL)
//
//   din --[ A = a2 o a1 : 6 invertible rounds ]--> (s1_q, en) --[ B: short ]--> (s2_q, en)
//
// Both registers carry a clock enable.  The register cut is unbalanced: six
// rounds in front of s1_q, almost nothing in front of s2_q.
//
// Rebalancing means moving s1_q backward through a2 -- and the enable has to move
// with it, coherently, or the design breaks the first time `en` is low.
//
// Two things make this awkward for a tool:
//   * gf180mcu has NO enable flip-flop in the library.  The enable becomes a
//     recirculating mux feeding a plain dffq, so the register to be retimed sits
//     inside a combinational mux loop.  Genus has a dedicated attribute for this
//     (retime_move_mux_loop_with_reg), which tells you it is a known hard case.
//   * On Artix-7 the enable maps onto FDRE.CE, and moving the register requires
//     re-deriving the enable expression at the new location.

module r17_clock_enable_barrier_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic        en,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  localparam logic [15:0] S1_RESET = 16'h0;

  logic [15:0] s1_q, s2_q;

  always_ff @(posedge clk) begin
    if (!rst_n)   s1_q <= S1_RESET;
    else if (en)  s1_q <= a2(a1(din));
  end

  always_ff @(posedge clk) begin
    if (!rst_n)   s2_q <= 16'h0;
    else if (en)  s2_q <= s1_q ^ {s1_q[7:0], s1_q[15:8]};
  end

  assign dout = s2_q;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r17_clock_enable_barrier_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r17_clock_enable_barrier (
    input  logic clk,
    input  logic rst_n,
    input  logic en,
    input  logic [15:0] din,
    output logic [15:0] dout
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic en_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] din_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dout_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      en_iq <= '0;
      din_iq <= '0;
    end else begin
      en_iq <= en;
      din_iq <= din;
    end
  end

  r17_clock_enable_barrier_core u_core (
    .clk(clk), .rst_n(rst_n),
    .en(en_iq),
    .din(din_iq),
    .dout(dout_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dout <= '0;
    end else begin
      dout <= dout_c;
    end
  end

endmodule
