// r17 -- clock_enable_barrier  (HAND-RETIMED REFERENCE)
//
//   din --[ a1: 3 rounds ]--> (p_q, en) --[ a2: 3 rounds ]--[ B ]--> (s2_q, en)
//
// s1_q moved backward through a2, taking its enable with it.  Two enabled
// registers before, two after; identical latency and identical behaviour for any
// enable waveform.
//
// Correctness argument
// --------------------
// The invariant maintained is
//
//     a2(p_q[t]) == s1_q[t]      for every cycle t
//
// * it holds at reset by choosing P_RESET = a2^-1(S1_RESET);
// * if en is high, p_q takes a1(din) while the original s1_q takes a2(a1(din)),
//   so the invariant is preserved;
// * if en is low, both registers hold, so it is preserved.
//
// Since stage 2 consumes only a2(p_q) in place of s1_q, the outputs agree
// cycle-for-cycle -- including across enable gaps and across reset.

module r17_clock_enable_barrier_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic        en,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] a1 (input logic [15:0] x);
    a1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a2 (input logic [15:0] x);
    a2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] a2_inv (input logic [15:0] y);
    a2_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] S1_RESET = 16'h0;
  localparam logic [15:0] P_RESET  = a2_inv(S1_RESET);

  logic [15:0] p_q, s2_q;
  logic [15:0] a2p;

  always_ff @(posedge clk) begin
    if (!rst_n)   p_q <= P_RESET;
    else if (en)  p_q <= a1(din);
  end

  always_comb a2p = a2(p_q);

  always_ff @(posedge clk) begin
    if (!rst_n)   s2_q <= 16'h0;
    else if (en)  s2_q <= a2p ^ {a2p[7:0], a2p[15:8]};
  end

  assign dout = s2_q;

endmodule

