// r02 -- reset_no_valid_init  (HAND-RETIMED REFERENCE, explicit reset circuitry)
//
//   PI --[ h1 ]--> (p_q) --[ h2 ]--[ & MASK ]--+
//                                              |--> mux --[ f ]--> (out_q)
//              (rst_seen_q) --------------------+
//
// Because no reset constant exists for a register moved past the mask (see the
// original), reset is removed from the moved register entirely and reintroduced
// as logic: a one-bit `rst_seen_q` flag selects the original reset value on
// exactly the cycle the downstream stage would have observed it.
//
// Correctness
// -----------
// In the original, out_q latches f(q). While reset is asserted q reads Q_RESET,
// so the first post-reset value of out_q is f(Q_RESET); thereafter out_q sees the
// masked datapath. The reference reproduces that by making the mux select
// Q_RESET exactly while rst_seen_q is set, so:
//
//   out_q[T+1] = f(Q_RESET)                 -- rst_seen_q still set
//   out_q[T+2] = f(h2(h1(din[T])) & MASK)   -- flag cleared, datapath selected
//
// which matches the original cycle for cycle, for every reset pulse, not just
// the first one.
//
// Cost: one extra flip-flop, and a 16-bit mux in the second stage.  That is the
// documented price of the explicit-reset transform, and it is why a tool weighs
// this move carefully rather than taking it for free.  p_q's own reset value is
// irrelevant -- it is always masked off by the mux -- so it resets to zero.

module r02_reset_no_valid_init_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] h1 (input logic [15:0] x);
    h1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] h2 (input logic [15:0] x);
    h2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  localparam logic [15:0] MASK    = 16'hFFFE;
  localparam logic [15:0] Q_RESET = 16'hBEEF;

  logic [15:0] p_q, out_q;
  logic        rst_seen_q;
  logic [15:0] q_eff;

  // Stage 1: only h1 now, and no reset value is required of it.
  always_ff @(posedge clk) begin
    if (!rst_n) p_q <= 16'h0;
    else        p_q <= h1(din);
  end

  // The explicit reset circuitry: one flag flop replacing a reset constant.
  always_ff @(posedge clk) begin
    if (!rst_n) rst_seen_q <= 1'b1;
    else        rst_seen_q <= 1'b0;
  end

  always_comb q_eff = rst_seen_q ? Q_RESET : (h2(p_q) & MASK);

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0;
    else        out_q <= q_eff ^ {q_eff[7:0], q_eff[15:8]};
  end

  assign dout = out_q;

endmodule

