// r02 -- reset_no_valid_init  (DIRECTIVE VARIANT)
// Original RTL; the tool is asked to perform the explicit-reset transform itself.
//
//   PI --[ h1 : 3 rounds ]--[ h2 : 3 rounds ]--[ & 0xFFFE ]--> (q, reset=0xBEEF) --[ f ]--> (out_q)
//
// Same unbalanced shape as r01, with one crucial difference: the last thing that
// happens before the register is an AND with 0xFFFE, so bit 0 of the register's
// data input is ALWAYS zero -- while the register's reset value 0xBEEF has bit 0
// set.
//
// Consequence: there is NO constant that the retimed register could reset to.
// Moving `q` backward past the mask requires the new register value v to satisfy
//
//     (v & 0xFFFE) == 0xBEEF
//
// whose left side always has bit 0 clear.  No solution exists.  This is not a
// tool limitation, it is the actual initial-state problem: a retiming can be
// delay-optimal and still have no equivalent initial state.
//
// The escape is to stop encoding reset in the flop and encode it in logic
// instead -- "explicit reset circuitry" -- which is what the reference does.

module r02_reset_no_valid_init_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] din,
    output logic [15:0] dout
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;

  function automatic logic [15:0] h1 (input logic [15:0] x);
    h1 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] h2 (input logic [15:0] x);
    h2 = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction

  // The mask is what destroys surjectivity, and 0xBEEF is odd.
  localparam logic [15:0] MASK    = 16'hFFFE;
  localparam logic [15:0] Q_RESET = 16'hBEEF;

  logic [15:0] q, out_q;

  always_ff @(posedge clk) begin
    if (!rst_n) q <= Q_RESET;
    else        q <= h2(h1(din)) & MASK;
  end

  always_ff @(posedge clk) begin
    if (!rst_n) out_q <= 16'h0;
    else        out_q <= q ^ {q[7:0], q[15:8]};
  end

  assign dout = out_q;

endmodule

