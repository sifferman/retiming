// r27 -- exception_scope_probe  (HAND-RETIMED REFERENCE)
//
// Pipeline A recut 3 / 3, pipeline B and its multicycle exception untouched.
// Two register stages per pipeline before and after, identical I/O latency.
//
// The reference deliberately retimes ONLY the pipeline that no constraint names.
// That is the transform a correct tool should be able to make while honouring
// B's exception, and it is the yardstick the probe measures against.
//
// Reset: douta reads zero after reset in the original (aq2 = aq1 ^ rot(aq1) with
// aq1 = 0).  After the recut, aq2 sees a3b(p), so p must reset to a3b^-1(0).

module r27_exception_scope_probe_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] dina,
    input  logic [15:0] dinb,
    output logic [15:0] douta,
    output logic [15:0] doutb
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;
  localparam logic [15:0] K7 = 16'hB7E1, C7 = 16'h51ED;
  localparam logic [15:0] K8 = 16'h2545, C8 = 16'hF491;

  // ---- Pipeline A: RETIMED, cut 3/3 instead of 6/0 ----
  function automatic logic [15:0] rnd_inv (input logic [15:0] y,
                                           input logic [15:0] k,
                                           input logic [15:0] c);
    logic [15:0] t;
    t       = (y - c) ^ k;
    rnd_inv = {t[0], t[15:1]};
  endfunction

  function automatic logic [15:0] a3a (input logic [15:0] x);
    a3a = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] a3b (input logic [15:0] x);
    a3b = rnd(rnd(rnd(x, K4, C4), K5, C5), K6, C6);
  endfunction
  function automatic logic [15:0] a3b_inv (input logic [15:0] y);
    a3b_inv = rnd_inv(rnd_inv(rnd_inv(y, K6, C6), K5, C5), K4, C4);
  endfunction

  localparam logic [15:0] AP_RESET = a3b_inv(16'h0);

  logic [15:0] ap, aq2;
  logic [15:0] am;

  always_ff @(posedge clk) begin
    if (!rst_n) ap <= AP_RESET;
    else        ap <= a3a(dina);
  end

  always_comb am = a3b(ap);

  always_ff @(posedge clk) begin
    if (!rst_n) aq2 <= 16'h0;
    else        aq2 <= am ^ {am[7:0], am[15:8]};
  end

  assign douta = aq2;

  // ---- Pipeline B: carries the multicycle exception ----
  function automatic logic [15:0] b3 (input logic [15:0] x);
    b3 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] b8 (input logic [15:0] x);
    b8 = rnd(rnd(rnd(rnd(rnd(rnd(rnd(rnd(
           x, K4, C4), K5, C5), K6, C6), K7, C7), K8, C8),
           K1, C1), K2, C2), K3, C3);
  endfunction

  logic [15:0] bq1, bq2;

  always_ff @(posedge clk) begin
    if (!rst_n) bq1 <= 16'h0;
    else        bq1 <= b3(dinb);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) bq2 <= 16'h0;
    else        bq2 <= b8(bq1);
  end

  assign doutb = bq2;

endmodule

// RT_WRAPPER_BEGIN -- generated by scripts/add_io_registers.py
// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r27_exception_scope_probe_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r27_exception_scope_probe (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] dina,
    input  logic [15:0] dinb,
    output logic [15:0] douta,
    output logic [15:0] doutb
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dina_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dinb_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] douta_c;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] doutb_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dina_iq <= '0;
      dinb_iq <= '0;
    end else begin
      dina_iq <= dina;
      dinb_iq <= dinb;
    end
  end

  r27_exception_scope_probe_core u_core (
    .clk(clk), .rst_n(rst_n),
    .dina(dina_iq),
    .dinb(dinb_iq),
    .douta(douta_c),
    .doutb(doutb_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      douta <= '0;
      doutb <= '0;
    end else begin
      douta <= douta_c;
      doutb <= doutb_c;
    end
  end

endmodule
