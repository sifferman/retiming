// r27 -- exception_scope_probe  (ORIGINAL)  [DIAGNOSTIC BENCHMARK]
//
//   Pipeline A:  dina --[ 6 rounds ]--> (aq1) --[ trivial ]--> (aq2)   <- unbalanced,
//                                                                        wants retiming,
//                                                                        NOT named in any SDC exception
//
//   Pipeline B:  dinb --[ 3 rounds ]--> (bq1) --[ 8 rounds ]--> (bq2)  <- carries a
//                                                                        multicycle exception
//                                                                        naming bq1/bq2
//
// The two pipelines share nothing but the clock.
//
// r26 established that when a multicycle exception names the registers on a path,
// Genus reports RETIME-402 ("the design does not contain retimeable flops") and
// does no retiming -- ending up with worse timing than the same RTL without the
// exception.  What r26 cannot tell us is the SCOPE of that exclusion, because both
// of its register stages are named in the exception.
//
// This benchmark answers it.  Pipeline A is plainly retimable and no constraint
// mentions it:
//
//   * if A gets retimed, the exclusion is path-local, and the practical advice is
//     "keep timing exceptions off paths you want retimed";
//   * if A does not get retimed, then one exception anywhere in the design
//     disables retiming everywhere -- a far more serious limitation, and a
//     complete explanation for a retimer that appears to do nothing on a large
//     design that has any exceptions at all.
//
// The measurement is the presence of `retime_*` registers in pipeline A, not Fmax.

module r27_exception_scope_probe_core (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [15:0] dina,
    input  logic [15:0] dinb,
    output logic [15:0] douta,
    output logic [15:0] doutb
);

  function automatic logic [15:0] rnd (input logic [15:0] x,
                                       input logic [15:0] k,
                                       input logic [15:0] c);
    logic [15:0] t;
    t   = {x[14:0], x[15]} ^ k;
    rnd = t + c;
  endfunction

  localparam logic [15:0] K1 = 16'h9E37, C1 = 16'h1234;
  localparam logic [15:0] K2 = 16'h7B15, C2 = 16'h5A5A;
  localparam logic [15:0] K3 = 16'hC2B2, C3 = 16'h0F1E;
  localparam logic [15:0] K4 = 16'h27D4, C4 = 16'hBEEF;
  localparam logic [15:0] K5 = 16'h1656, C5 = 16'h3C3C;
  localparam logic [15:0] K6 = 16'h6763, C6 = 16'h07E1;
  localparam logic [15:0] K7 = 16'hB7E1, C7 = 16'h51ED;
  localparam logic [15:0] K8 = 16'h2545, C8 = 16'hF491;

  // ---- Pipeline A: unbalanced, unconstrained by exceptions ----
  function automatic logic [15:0] a6 (input logic [15:0] x);
    a6 = rnd(rnd(rnd(rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3), K4, C4),
                 K5, C5), K6, C6);
  endfunction

  logic [15:0] aq1, aq2;

  always_ff @(posedge clk) begin
    if (!rst_n) aq1 <= 16'h0;
    else        aq1 <= a6(dina);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) aq2 <= 16'h0;
    else        aq2 <= aq1 ^ {aq1[7:0], aq1[15:8]};
  end

  assign douta = aq2;

  // ---- Pipeline B: carries the multicycle exception ----
  function automatic logic [15:0] b3 (input logic [15:0] x);
    b3 = rnd(rnd(rnd(x, K1, C1), K2, C2), K3, C3);
  endfunction
  function automatic logic [15:0] b8 (input logic [15:0] x);
    b8 = rnd(rnd(rnd(rnd(rnd(rnd(rnd(rnd(
           x, K4, C4), K5, C5), K6, C6), K7, C7), K8, C8),
           K1, C1), K2, C2), K3, C3);
  endfunction

  logic [15:0] bq1, bq2;

  always_ff @(posedge clk) begin
    if (!rst_n) bq1 <= 16'h0;
    else        bq1 <= b3(dinb);
  end

  always_ff @(posedge clk) begin
    if (!rst_n) bq2 <= 16'h0;
    else        bq2 <= b8(bq1);
  end

  assign doutb = bq2;

endmodule

