// ---------------------------------------------------------------------
// Every input is captured and every output is registered, so ALL logic in
// r27_exception_scope_probe_core lies between flip-flops and reg2reg timing sees all of it.
// Applied identically to every variant, so the variants remain equivalent
// to one another; each simply gains the same 2 cycles of latency.
// ---------------------------------------------------------------------
module r27_exception_scope_probe (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] dina,
    input  logic [15:0] dinb,
    output logic [15:0] douta,
    output logic [15:0] doutb
);
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dina_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] dinb_iq;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] douta_c;
  (* dont_touch = "yes", RETIMING_FORWARD = 0, RETIMING_BACKWARD = 0 *)
  logic [15:0] doutb_c;

  // capture inputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      dina_iq <= '0;
      dinb_iq <= '0;
    end else begin
      dina_iq <= dina;
      dinb_iq <= dinb;
    end
  end

  r27_exception_scope_probe_core u_core (
    .clk(clk), .rst_n(rst_n),
    .dina(dina_iq),
    .dinb(dinb_iq),
    .douta(douta_c),
    .doutb(doutb_c)
  );

  // register outputs
  always_ff @(posedge clk) begin
    if (!rst_n) begin
      douta <= '0;
      doutb <= '0;
    end else begin
      douta <= douta_c;
      doutb <= doutb_c;
    end
  end

endmodule
