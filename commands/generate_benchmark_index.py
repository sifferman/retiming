#!/usr/bin/env python3
"""Generate docs/INDEX.md: one row per benchmark, with its current measured status.

Auto-generated so it cannot drift from the benchmarks or the results.  Regenerate
with `make index` after any measurement run.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from benchmark_lib.benchmark import Benchmark

import csv
import re
from collections import defaultdict

ROOT = Path(__file__).resolve().parent.parent

def load_meta(benchmark_directory):
    return Benchmark(benchmark_directory).fields

def first_para(text):
    """The description block from bench.yaml, flattened to one line."""
    return " ".join(text.split())

def main():
    benches = sorted(p for p in (ROOT / "benchmarks").iterdir()
                     if (p / "variants" / "orig").is_dir())

    status = defaultdict(dict)
    summ = ROOT / "results" / "summary.csv"
    if summ.exists():
        for r in csv.DictReader(summ.open()):
            if r["tool"] != "genus":
                continue
            key = r["bench"]
            try:
                fm = float(r["fmax_mhz"])
            except (ValueError, KeyError):
                continue
            slot = "ref" if r["variant"] == "retimed" else "tool"
            cur = status[key].get(slot)
            if cur is None or fm > cur[0]:
                status[key][slot] = (fm, r.get("fmax_is_lower_bound") == "yes")

    lines = [
        "# Benchmark Index",
        "",
        "Auto-generated by `commands/generate_benchmark_index.py` (`make index`). One row per",
        "benchmark with its declared class, primary metric, and the current measured",
        "Genus Fmax for the best tool configuration versus the hand-written reference.",
        "",
        "`>=` marks a figure that is a **lower bound** — the tightest swept period still",
        "met timing, so the true value is higher and the comparison is not conclusive.",
        "Benchmarks scored on power or wirelength show `--` here; see `docs/FINDINGS.md`.",
        "",
        "| ID | benchmark | class | metric | latency | tool Fmax | ref Fmax |",
        "|----|-----------|-------|--------|---------|-----------|----------|",
    ]

    for b in benches:
        m = load_meta(b)
        bid = m.get("id", b.name.split("_")[0])
        cls = (m.get("class") or "").strip('"')
        metric = m.get("primary_metric", "fmax")
        lat = "strict" if str(m.get("latency_preserving", "")).lower() == "true" \
              else f"+{m.get('latency_delta', '?')} cyc"
        st = status.get(b.name, {})

        def fmt(slot):
            if metric != "fmax" or slot not in st:
                return "--"
            v, bounded = st[slot]
            return f"{'>=' if bounded else ''}{v:.0f} MHz"

        lines.append(f"| {bid} | `{b.name}` | {cls} | {metric} | {lat} "
                     f"| {fmt('tool')} | {fmt('ref')} |")

    lines += ["", "## What each benchmark tests", ""]
    for b in benches:
        m = load_meta(b)
        txt = (b / "bench.yaml").read_text()
        desc = re.search(r"^description:\s*\|\s*\n((?:  .*\n)+)", txt, re.M)
        exp = re.search(r"^expected:\s*\|\s*\n((?:  .*\n)+)", txt, re.M)
        lines.append(f"### `{b.name}`")
        lines.append("")
        if desc:
            lines.append(f"**Stressor.** {first_para(desc.group(1))}")
            lines.append("")
        if exp:
            lines.append(f"**Expectation / result.** {first_para(exp.group(1))}")
            lines.append("")

    (ROOT / "docs" / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"wrote docs/INDEX.md ({len(benches)} benchmarks)")

if __name__ == "__main__":
    main()
